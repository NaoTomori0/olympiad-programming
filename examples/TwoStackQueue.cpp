struct Node
{
    int value, max;
};

// очередь из двух стеков использует по разному, в каждой задаче решение с очередью из двух стеков
// может сильно отличатся
struct TwoStackQueue
{
    void push(int x) { stain.push({x, stain.empty() ? x : max(stain.top().max, x)}); };

    void remove()
    {
        move1to2();
        staout.pop();
    }

    Node getCurNode()
    {
        move1to2();
        return staout.top();
    }

    int get_max()
    {
        if (stain.empty() && staout.empty())
            return -1;
        if (stain.empty())
            return staout.top().max;
        if (staout.empty())
            return stain.top().max;
        return max(stain.top().max, staout.top().max);
    }

private:
    stack<Node> stain, staout; //  можно использовать vector, но если хотите обезопасить себя то можно явно использовать stack

    void move1to2()
    {
        if (staout.empty())
            while (!stain.empty())
            {
                Node n = stain.top();
                stain.pop();
                staout.push({n.value, staout.empty() ? n.max : max(n.max, staout.top().max)});
            }
    }
};

