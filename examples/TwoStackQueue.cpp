// Очередь на двух стеках — это структура данных, которая работает по принципу FIFO
// (первым вошёл — первым вышел), но строится на базе двух стеков с принципом LIFO
// (последним вошёл — первым вышел).

// ======================================================================
// Идея
// ======================================================================

// Используются два стека:

// - Стек для добавления (push_stack) — в него добавляются новые элементы.
// - Стек для извлечения (pop_stack) — из него извлекаются элементы.

// При операции добавления элемент просто кладётся в push_stack.

// При операции извлечения:
// - Если pop_stack пуст, то все элементы из push_stack перекладываются в pop_stack
//   (при этом порядок элементов меняется на обратный).
// - Затем извлекается верхний элемент из pop_stack.

// Таким образом, первый добавленный элемент оказывается на вершине pop_stack
// и извлекается первым, что соответствует FIFO.

// ======================================================================
// Операции и их сложность
// ======================================================================

// - push(x): добавить элемент x в очередь.
//   Сложность: O(1) — просто положить в push_stack.

// - pop(): удалить и вернуть первый элемент очереди.
//   Амортизированная сложность: O(1).
//   В худшем случае (когда pop_stack пуст) требуется переложить все элементы
//   из push_stack в pop_stack, что занимает O(n), но каждый элемент перекладывается
//   не более одного раза, поэтому амортизированное время — O(1) на операцию.

// - front(): вернуть первый элемент без удаления.
//   Аналогично pop(), но без извлечения из pop_stack.

// - empty(): проверить, пуста ли очередь.
//   O(1) — проверить, пусты ли оба стека.

// ======================================================================
// Преимущества и недостатки
// ======================================================================

// - Преимущества: простота реализации, эффективная амортизированная сложность,
//   возможность использования в языках, где нет встроенной очереди.
// - Недостатки: в худшем случае операция извлечения может быть дорогой
//   (но это случается редко), требуется дополнительная память для двух стеков.

// ======================================================================
// Применение
// ======================================================================

// - Когда встроенная очередь недоступна, а требуется FIFO.
// - В некоторых алгоритмах, где очередь нужна, но удобнее использовать стеки
//   (например, при обходе в ширину с дополнительными ограничениями).
// - В задачах, где требуется амортизированная O(1) сложность операций.

