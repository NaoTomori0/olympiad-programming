// Поиск в глубину (Depth-First Search, DFS) — это один из базовых алгоритмов обхода
// графов и деревьев. Стратегия алгоритма заключается в том, чтобы идти вглубь одного
// пути до тех пор, пока это возможно, а затем возвращаться назад (бектрекинг) для
// исследования других веток.

// ======================================================================
// Ключевые особенности DFS
// ======================================================================

// - Обход графа в глубину: сначала посещается одна ветвь до конца, затем
//   происходит возврат и переход к следующей.
// - Использует стек (явный или рекурсивный) для хранения вершин.
// - Не гарантирует нахождение кратчайшего пути.
// - Временная сложность: O(V + E), где V — количество вершин, E — количество рёбер.

// ======================================================================
// Алгоритм (рекурсивная версия)
// ======================================================================

// 1. Начать с заданной вершины, отметить её как посещённую.
// 2. Для каждой смежной непосещённой вершины рекурсивно применить DFS.
// 3. После обработки всех смежных вершин возврат к предыдущей вершине.
// 4. Повторять, пока все вершины не будут посещены.

// ======================================================================
// Алгоритм (итеративная версия со стеком)
// ======================================================================

// 1. Поместить стартовую вершину в стек и отметить её как посещённую.
// 2. Пока стек не пуст:
//    - Извлечь вершину из стека.
//    - Обработать её.
//    - Для каждой смежной непосещённой вершины:
//      - Отметить её как посещённую.
//      - Поместить её в стек.
// 3. Алгоритм завершается, когда стек становится пустым.

// ======================================================================
// Применение
// ======================================================================

// - Поиск компонент связности.
// - Проверка наличия циклов в графе.
// - Топологическая сортировка.
// - Поиск путей и решение задач на лабиринтах.
// - Генерация всех возможных комбинаций (бектрекинг).

// Пример на неорентированном не взвешенном графе

#include <bits/stdc++.h>
using namespace std;

#define int long long

