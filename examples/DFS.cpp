void DFS(vector<vector<int>> &graph, vector<bool> &visited, int v)
{
    visited[v] = 1;

    for (auto &u : graph[v])
        if (!visited[u])
            DFS(graph, visited, u);
}

void recursive_solve()
{
    int V, E;
    cin >> V >> E;
    vector<vector<int>> graph(V); // vector<vector<Edge>> graph(V);
    for (int i = 0; i < E; i++)
    {
        // Edge e;
        int from, to;
        cin >> from >> to;
        from--;
        to--; // перевод в 0-ую индексацию
        graph[from].push_back(to);
        graph[to].push_back(from);
    }
    int start;
    cin >> start;
    start--;
    vector<bool> visited(V, 0);
    DFS(graph, visited, start);
}

void iterative_solve()
{
    int V, E;
    cin >> V >> E;
    vector<vector<int>> graph(V);
    for (int i = 0; i < E; i++)
    {
        int from, to;
        cin >> from >> to;
        from--;
        to--;
        graph[from].push_back(to);
        graph[to].push_back(from);
    }
    int start;
    cin >> start;
    start--;
    vector<bool> visited(V, 0);

    stack<int> st;
    st.push(start);
    visited[start] = 1;

    while (!st.empty())
    {
        int cur_v = st.top();
        st.pop();

        for (auto &u : graph[cur_v])
            if (!visited[u])
            {
                visited[u] = 1;
                st.push(u);
            }
    }
}

int32_t main()
{
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);

    recursive_solve();
    return 0;
}
