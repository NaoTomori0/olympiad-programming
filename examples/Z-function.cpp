// Z-функция строки — это массив чисел, где каждое число z[i] равно длине наибольшего
// префикса строки, который совпадает с подстрокой, начинающейся с позиции i.

// ======================================================================
// Определение
// ======================================================================

// Пусть дана строка s длины n. Z-функция — это массив z[0..n-1], где:

// - z[0] = 0 (по определению, для полной строки обычно не рассматривают префикс,
//   совпадающий с самой собой).
// - Для i > 0: z[i] = max{ k | k ≥ 0, s[0..k-1] = s[i..i+k-1] }.

// Другими словами, z[i] — длина наибольшего общего префикса строки s и её суффикса,
// начинающегося в позиции i.

// ======================================================================
// Пример
// ======================================================================

// Пусть s = "abacaba".

// Вычислим z-функцию:

// i = 0: z[0] = 0
// i = 1: подстрока "bacaba" не совпадает с началом, z[1] = 0
// i = 2: подстрока "acaba" — первый символ 'a' совпадает с s[0]='a',
//        далее 'c' ≠ 'b', значит z[2] = 1
// i = 3: "caba" — первый символ 'c' ≠ 'a', z[3] = 0
// i = 4: "aba" — совпадает с "aba", z[4] = 3
// i = 5: "ba" — 'b' ≠ 'a', z[5] = 0
// i = 6: "a" — совпадает с 'a', z[6] = 1

// Итоговая Z-функция: [0, 0, 1, 0, 3, 0, 1]

// ======================================================================
// Применение
// ======================================================================

// - Поиск всех вхождений образца в тексте (конкатенация pattern + '#' + text).
// - Поиск наименьшего периода строки.
// - Сравнение подстрок (с помощью Z-функции).
// - Поиск количества различных подстрок (совместно с другими методами).
// - Решение задач на нахождение наибольшего общего префикса.

#include <bits/stdc++.h>
using namespace std;

#define int long long

vector<int> Zfunction(string s)
{
    int n = s.size();
    vector<int> z(n);
    int l = 0, r = 0;
    for (int i = 1; i < n; i++)
    {

        if (i <= r)
            z[i] = min(r - i + 1, z[i - l]); // берем либо уже высчитанное значение из z
        // если текущеее значение выходит за рамки нашего высчитанного окна
        // иначе r - i + 1

        // тупо сравниваем суффикс с преффиксом по символьно
        // i + z[i] < n что бы не выйти за границу строки
        while (i + z[i] < n && s[z[i]] == s[z[i] + i])
            z[i]++;

        // если вышли за текущее рабочее окно, то обновляем его границы
        if (r < z[i] + i - 1)
        {
            l = i;
            r = z[i] + i - 1;
        }
    }

    return z;
}

