// Поиск в ширину (BFS)
// ограничение по времени на тест - (теоретический материал)
// ограничение по памяти на тест - (теоретический материал)

// Поиск в ширину (Breadth-First Search, BFS) — это базовый алгоритм обхода графов
// или деревьев, который исследует узлы по уровням. Он начинает с заданной вершины
// и сначала посещает всех её ближайших соседей, прежде чем переходить к узлам
// следующего уровня.

// Для визуализации процесса часто используется очередь (FIFO — First In, First Out):
// новые вершины добавляются в конец очереди, а извлекаются и обрабатываются из её
// начала.

// ======================================================================
// Ключевые особенности BFS
// ======================================================================

// - Обход графа по уровням (слоям): сначала вершины на расстоянии 1 от стартовой,
//   затем на расстоянии 2 и т.д.
// - Использует очередь для хранения вершин, ожидающих обработки.
// - Позволяет находить кратчайшие пути в невзвешенных графах (в рёбрах).
// - Временная сложность: O(V + E), где V — количество вершин, E — количество рёбер.

// ======================================================================
// Алгоритм
// ======================================================================

// 1. Поместить стартовую вершину в очередь и отметить её как посещённую.
// 2. Пока очередь не пуста:
//    - Извлечь вершину из начала очереди.
//    - Обработать её (например, вывести или проверить условие).
//    - Для каждой смежной непосещённой вершины:
//      - Отметить её как посещённую.
//      - Добавить её в конец очереди.
// 3. Алгоритм завершается, когда очередь становится пустой.

// Пример на неорентированном не взвешенном графе

#include <bits/stdc++.h>
using namespace std;

#define int long long

// struct Edge
// {
//     int to;
//     double weight;
// };

void solve()
{
    int V, E;
    cin >> V >> E;
    vector<vector<int>> graph(V); // vector<vector<Edge>> graph(V);
    for (int i = 0; i < E; i++)
    {
        // Edge e;
        int from, to;
        cin >> from >> to;
        from--;
        to--; // перевод в 0-ую индексацию
        graph[from].push_back(to);
        graph[to].push_back(from);
    }
    int start;
    cin >> start;
    vector<bool> visited(V, 0);

    queue<int> q;
    q.push(--start);
    visited[start] = 1;
    while (!q.empty()) // обход всех вершин
    {
        int cur_v = q.front();
        q.pop();
        cout << cur_v << '\n';

        for (auto &u : graph[cur_v])
            if (!visited[u])
            {
                visited[u] = 1;
                q.push(u);
            }
    }
}

int32_t main()
{
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);

    solve();
    return 0;
}
