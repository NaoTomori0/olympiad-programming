// D. Количество хороших подстрок - 1
// ограничение по времени на тест2 секунды
// ограничение по памяти на тест256 мегабайт

// В дальнейшем эта задача будет предложена в больших ограничениях.
// Пока же для ознакомления с терминологией эту задачу вам предлагается решить в небольших ограничениях.

// Вам заданы две строки s и t. Назовём подстроку строки s[i…j] хорошей, если она не содержит в качестве подстроки строку t.
// Одинаковые по содержимому, но разные по позициям подстроки следует учитывать столько раз, сколько они встречаются в строке s.
// Иными словами, вам надо найти количество таких пар индексов (i,j) (i≤j), что подстрока s[i…j] не содержит вхождение t.

// Входные данные
// В первой строке входных данных записано целое число q (1≤q≤100) — количество наборов входных данных в тесте.

// Каждый набор входных данных состоит из двух строк s и t. Длина строки s от 1 до 50000 символов, длина строки t от 1 до 100 символов.
// Строки s и t состоят исключительно из строчных букв латинского алфавита.

// Сумма длин строк по всем s наборам входных данных в тесте не превосходит 50000.
// Аналогично, сумма длин строк по всем t наборам входных данных в тесте не превосходит 100.

// Выходные данные
// Выведите q целых чисел — для каждой строки выведите искомое количество подстрок.

// ======================================================================
// Примеры
// ======================================================================
// Входные данные
// ======================================================================
// 4
// zaza
// az
// abacaba
// ab
// aaaaa
// a
// aaa
// b
// ======================================================================
// Выходные данные
// ======================================================================
// 6
// 14
// 0
// 6

// ======================================================================
// Входные данные
// ======================================================================
// 8
// abbbbabbbabb
// b
// ababbaa
// ab
// az
// az
// z
// a
// a
// aa
// ababaaba
// aba
// abcdefgh
// fgh
// abacabadaba
// ba
// ======================================================================
// Выходные данные
// ======================================================================
// 3
// 14
// 2
// 1
// 1
// 19
// 30
// 24
// ======================================================================

#include <iostream>
#include <string>
#include <vector>
#include <algorithm>

void solve()
{
    std::string s, t;
    std::cin >> s >> t;

    int n = s.length();
    int m = t.length();

    std::vector<int> positions;
    size_t pos = s.find(t, 0);
    while (pos != std::string::npos)
    {
        positions.push_back(static_cast<int>(pos));
        pos = s.find(t, pos + 1);
    }

    long long good_substrings_count = 0;

    for (int i = 0; i < n; ++i)
    {
        auto it = std::lower_bound(positions.begin(), positions.end(), i);

        if (it != positions.end())
        {
            int j = *it;
            int last_good_end = j + m - 2;
            if (last_good_end >= i)
            {
                good_substrings_count += (last_good_end - i + 1);
            }
        }
        else
        {
            good_substrings_count += (n - i);
        }
    }

    std::cout << good_substrings_count << "\n";
}

int main()
{
    // Ускорение ввода-вывода
    std::ios_base::sync_with_stdio(false);
    std::cin.tie(NULL);

    int q;
    if (std::cin >> q)
    {
        while (q--)
        {
            solve();
        }
    }
    return 0;
}
