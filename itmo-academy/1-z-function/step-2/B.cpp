// B. Z-функция строки Грея
// ограничение по времени на тест2 секунды
// ограничение по памяти на тест512 мегабайт

// Эта задача не требует знания эффективного алгоритма нахождения z-функции.
// Достаточно только понимания определения, чтобы решить эту задачу.

// Последовательность строк Грея g1,g2,… выглядит следующим образом:

// g1 = «a»
// g2 = «aba»
// g3 = «abacaba»
// g4 = «abacabadabacaba»
// ...
// gi = gi−1 + ci + gi−1, где ci — это i-й символ алфавита
// ...

// Заметим, что длины строки Грея очень быстро растут (длина i-й строки равна 2^i − 1),
// но они имеют регулярную фрактальную структуру.

// Часто на строках Грея удобно разбирать работу различных строковых алгоритмов.

// В этой задаче вам надо по заданному индексу k строки Грея и по числу j вывести zj —
// значение z-функции строки gk в индексе j.

// Входные данные
// В первой строке входных данных записано целое число t (1 ≤ t ≤ 10^4) — количество
// наборов входных данных в тесте.

// Каждый набор входных данных состоит из строки, в которой записаны два целых числа k и j
// (1 ≤ k ≤ 26, 0 ≤ j < 2^k − 1).

// Выходные данные
// Выведите t целых чисел — ответы для наборов входных данных в тесте, то есть значение
// z-функции для gk в индексе j.

// ======================================================================
// Пример
// ======================================================================
// Входные данные
// ======================================================================
// 8
// 1 0
// 2 0
// 2 1
// 2 2
// 3 0
// 3 3
// 3 6
// 3 4
// ======================================================================
// Выходные данные
// ======================================================================
// 0
// 0
// 0
// 1
// 0
// 0
// 1
// 3
// ======================================================================

// k   0 1 2   3       4               5
// res 0 0 1 0 3 0 1 0 7 0 1 0 3 0 1 015 0 1 0 3 0 1 0 7 0 1 0 3 0 1 0
// j   0 1 2 3 4 5 6 7 8 910111213141516171819202122232425262728293031

// ============================================================================
// РАЗБОР МАТЕМАТИЧЕСКОЙ ЗАКОНОМЕРНОСТИ:
// Посмотрим на значения Z-функции строки Грея для индексов j:
// - Если j = 0, то по определению Z-функции ответ всегда 0.
// - Если j > 0, значение Z[j] зависит от количества младших нулевых битов j.
// Чтобы увидеть закономерность, посмотрим на число в 1-индексации (x = j + 1):
// - Если j=1 => x=2 (в битах 00010). Делится на 2^1. Ответ: 0.
// - Если j=2 => x=3 (в битах 00011). Не делится на 2. Ответ: 1.
// - Если j=3 => x=4 (в битах 00100). Делится на 2^2. Ответ: 0.
// - Если j=4 => x=5 (в битах 00101). Не делится на 2. Ответ: 3.
// - Если j=5 => x=6 (в битах 00110). Делится на 2^1. Ответ: 0.
// - Если j=6 => x=7 (в битах 00111). Не делится на 2. Ответ: 1.
// - Если j=8 => x=9 (в битах 01001). Не делится на 2. Ответ: 7.

// МАГИЧЕСКОЕ ПРАВИЛО:
// 1. Если число x = j + 1 является четным, то ответ всегда 0.
// 2. Если число x = j + 1 является нечетным, то ответ равен 2^A - 1,
//    где A — количество младших нулевых битов в исходном числе j.

// Формулировка через функцию GCC __builtin_ctzll (подсчет младших нулей):
// Ответ всегда равен: (1LL << __builtin_ctzll(j)) - 1
// ============================================================================

// ============================================================================
// РЕШЕНИЕ НА ПАЛЬЦАХ ДЛЯ ВСЕХ
//
// Строка Грея строится по принципу «отражения» через центральную букву:
// g1 = "a"
// g2 = "a" + "b" + "a" = "aba"
// g3 = "aba" + "c" + "aba" = "abacaba"
// g4 = "abacaba" + "d" + "abacaba" = "abacabadabacaba"
//
// Строка состоит из одинаковых кусков, разделенных уникальными центрами (b, c, d...).
// Z-функция в точке j спрашивает: «Если отрезать кусок строки с позиции j,
// насколько сильно его начало похоже на самое начало всей строки (на кусок "aba...")?»
//
// ТУТ ВСЕГО ДВА ВАРИАНТА:
//
// 1. Мы попали на "центральную" букву (b, c, d...)
//    Вся строка начинается с буквы 'a'. А центральные буквы всегда другие.
//    Они не совпадают с началом строки, поэтому ответ всегда 0.
//    Это происходит на всех нечетных индексах j (1, 3, 5, 7...).
//
// 2. Мы попали на начало какого-то старого скопированного блока
//    В строке "abacaba" на индексе 4 снова начинается блок "aba".
//    Он точь-в-точь как начало всей строки. Его длина — 3 символа. Ответ: 3.
//
// КАК УЗНАТЬ ОТВЕТ ПО ЧИСЛУ J?
// Все блоки привязаны к степеням двойки (2, 4, 8, 16...). Смотрим, на какую
// максимальную степень двойки делится наш индекс j:
//
// - Если j делится на 2 (2, 6, 10, 14...) — это начало блока "a".
//   Длина совпадения: 2^1 - 1 = 1. Ответ: 1.
// - Если j делится на 4 (4, 12, 20...) — это начало блока "aba".
//   Длина совпадения: 2^2 - 1 = 3. Ответ: 3.
// - Если j делится на 8 (8, 24...) — это начало блока "abacaba".
//   Длина совпадения: 2^3 - 1 = 7. Ответ: 7.
//
// В коде за это отвечает функция __builtin_ctzll(j). Она считает, сколько раз
// число j делится на 2. Если делится на 4 (то есть 2^2), функция вернет 2.
// Тогда мы возводим 2 в степень 2 (получаем 4) и вычитаем 1. Ответ: 3.
// ============================================================================

#include <iostream>

void solve()
{
    long long k, j;
    std::cin >> k >> j;

    if (j == 0)
    {
        std::cout << 0 << "\n";
        return;
    }

    // Вычисляем количество младших нулевых битов за O(1)
    int trailing_zeros = __builtin_ctzll(j);
    long long ans = (1LL << trailing_zeros) - 1;

    std::cout << ans << "\n";
}

int main()
{
    // Ускорение стандартного ввода-вывода
    std::ios_base::sync_with_stdio(false);
    std::cin.tie(NULL);

    int t;
    std::cin >> t;
    while (t--)
    {
        solve();
    }

    return 0;
}
