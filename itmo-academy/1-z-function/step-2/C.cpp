// C. Строка по z-функции
// ограничение по времени на тест2 секунды
// ограничение по памяти на тест512 мегабайт

// Эта задача не требует знания эффективного алгоритма нахождения z-функции.
// Достаточно только понимания определения, чтобы решить эту задачу.

// Задан массив z длины n (1 ≤ n ≤ 50) из целых чисел от 0 до 50.
// Определите, существует ли такая строка s, что её z-функция равна z.
// Если такая строка существует, то выведите любую такую строку.
// Используйте прописные и строчные буквы латинского алфавита в качестве символов строки s.

// Входные данные
// В первой строке входных данных записано целое число t (1 ≤ t ≤ 10^4) — количество
// наборов входных данных в тесте.

// Каждый набор входных данных состоит из двух строк. В первой строке записано целое
// число n (1 ≤ n ≤ 50) — длина массива z. Во второй строке содержатся целые числа
// z0, z1, …, z_{n-1} (0 ≤ z_i ≤ 50).

// Выходные данные
// Выведите t строк. Очередная строка должна содержать «!», если искомой строки s
// не существует. В противном случае выведите любую подходящую строку s, которая
// состоит из прописных и строчных букв латинского алфавита.

// ======================================================================
// Пример
// ======================================================================
// Входные данные
// ======================================================================
// 5
// 15
// 0 0 1 0 3 0 1 0 7 0 1 0 3 0 1
// 6
// 0 0 0 0 0 0
// 5
// 0 4 3 2 1
// 1
// 50
// 2
// 1 1
// ======================================================================
// Выходные данные
// ======================================================================
// abacabazabacaba
// abcdef
// eeeee
// !
// !
// ======================================================================

// ============================================================================
// ОПИСАНИЕ СВОЙСТВ МАССИВА Z-ФУНКЦИИ
// Каждое число в массиве накладывает жесткие ограничения на символы строки.
// Если значение Z[i] равно 0, это означает запрет на совпадение подстроки с префиксом.
// Если значение Z[i] больше 0, это означает требование равенства символов строки.
// Подстрока длины Z[i] начиная с позиции i должна посимвольно копировать начало строки.
// Так как длина строки N очень маленькая (до 50), задачу можно решить жадным путем.
// ============================================================================

// ============================================================================
// ПОШАГОВЫЙ ПРИНЦИП ПОСТРОЕНИЯ СТРОКИ
// Сначала выполняется базовая проверка массива на корректность и вылет за границы.
// Первым шагом создается строка, заполненная полностью уникальными буквами алфавита.
// Использование уникальных букв (a-z, A-Z) автоматически гарантирует выполнение нулей.
// Вторым шагом запускается цикл слева направо для обработки всех условий равенства.
// Если значение Z[i] больше 0, префикс строки копируется поверх уникальных символов.
// Посимвольное копирование строго слева направо правильно распространяет связи равенства.
// Третьим шагом готовая строка обязательно перепроверяется честным подсчетом Z-функции.
// Если вычисленный массив не совпал с исходным, значит был подан невозможный чертеж.
// Программа отлавливает скрытые противоречия неравенств и в таком случае выводит знак «!».
// ============================================================================

#include <iostream>
#include <string>
#include <vector>

std::vector<int> zFoo(std::string s)
{
    int n = s.length();
    std::vector<int> result(n, 0);
    for (int i = 1; i < n; ++i)
    {
        int len = 0;
        while (i + len < n && s[len] == s[i + len])
        {
            ++len;
        }
        result[i] = len;
    }
    return result;
}

std::string solve(std::vector<int> data)
{
    int n = data.size();

    if (data[0] != 0)
        return "!";
    for (int i = 0; i < n; ++i)
    {
        if (i + data[i] > n)
            return "!"; // Вылет за границу строки
    }

    // Создаем пустую строку нужной длины
    std::string result(n, '?');
    char current_char = 'a';

    for (int i = 0; i < n; ++i)
    {
        result[i] = current_char;
        // a-z, затем A-Z, чтобы символы гарантированно не повторялись
        if (current_char == 'z')
            current_char = 'A';
        else
            current_char++;
    }

    for (int i = 0; i < n; ++i)
    {
        if (data[i] > 0)
        {
            for (int k = 0; k < data[i]; ++k)
            {
                // Символ в хвосте должен стать в точности таким же, как в префиксе
                result[i + k] = result[k];
            }
        }
    }
    for (int i = 0; i < n; i++)
    {
        if (result[i] == '?')
        {
            result[i] = current_char++;
        }
    }

    std::vector<int> check = zFoo(result);
    for (int i = 0; i < n; i++)
    {
        if (check[i] != data[i])
        {
            return "!";
        }
    }

    return result;
}

int main()
{
    // Ускорение ввода-вывода
    std::ios_base::sync_with_stdio(false);
    std::cin.tie(NULL);

    int t, n;
    std::cin >> t;
    for (int i = 0; i < t; ++i)
    {
        std::cin >> n;
        std::vector<int> nums;
        for (int j = 0; j < n; ++j)
        {
            int tmp;
            std::cin >> tmp;
            nums.push_back(tmp);
        }
        std::cout << solve(nums) << "\n";
    }

    return 0;
}