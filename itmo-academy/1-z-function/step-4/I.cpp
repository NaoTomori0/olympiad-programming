// I. Неточный поиск
// ограничение по времени на тест2 секунды
// ограничение по памяти на тест512 мегабайт

// Решите эту задачу с использованием z-функции строки. Существует много способов
// решить её, но в качестве упражнения на использование z-функции попробуйте
// придумать и реализовать именно такое решение.

// Задан текст t = t1 t2 … t_{|t|} и образец p = p1 p2 … p_{|p|}. Дополнительно задан
// параметр k.

// Если для индекса d верно, что t[d … d+|p|−1] = p, то существует точное вхождение p
// в t с индекса d.

// Для индекса d в подстроке t[d … d+|p|−1] существует такое окно (подстрока) из f
// символов, что в этом окне можно поменять 0 или более символов так (но длина окна
// остаётся неизменной), что подстрока t[d … d+|p|−1] станет равна p, и при этом f ≤ k,
// то в этом случае говорят о неточном вхождении образца в текст. Очевидно, что точное
// вхождение — это частный случай неточного.

// Например, если k = 3, t = «abacabadabacaba» и p = «baxayad», тогда есть одно неточное
// вхождение с индекса 2 (обратите внимание, что в этой задаче все индексы нумеруются
// от 1).

// Ваша задача — найти все неточные вхождения образца p в текст t.

// Входные данные
// Первая строка содержит t. Вторая строка содержит p. Обе строки состоят из букв
// латинского алфавита. Их длины от 1 до 10^6 включительно. Третья строка содержит
// целое число k (0 ≤ k ≤ 10^6).

// Выходные данные
// Выведите количество неточных вхождений и индексы их начал в возрастающем порядке.

// ======================================================================
// Примеры
// ======================================================================
// Входные данные
// ======================================================================
// abacaaa
// aaa
// 1
// ======================================================================
// Выходные данные
// ======================================================================
// 4
// 1 3 4 5

// ======================================================================
// Входные данные
// ======================================================================
// ababa
// aaaaa
// 3
// ======================================================================
// Выходные данные
// ======================================================================
// 1
// 1
// ======================================================================
#include <bits/stdc++.h> // Подключает сразу все библиотеки C++
using namespace std;

#define int long long // Защита от переполнения int

// Ваша исправленная Z-функция
vector<int> zfoo(string s)
{
    int n = s.length(), l = 0, r = 0;
    vector<int> z(n, 0);

    for (int i = 1; i < n; i++)
    {
        if (i <= r)
            z[i] = min(r + 1 - i, z[i - l]);

        while (z[i] + i < n && s[z[i]] == s[z[i] + i])
            z[i]++;

        if (z[i] + i - 1 > r)
        {
            l = i;
            r = z[i] + i - 1;
        }
    }
    return z;
}

void solve()
{
    string t, p;
    if (!(cin >> t >> p))
        return;
    int k;
    cin >> k; // Считываем параметр k

    int t_l = t.length();
    int p_l = p.length();

    // Если образец длиннее текста, вхождений быть не может
    if (p_l > t_l)
    {
        cout << 0 << "\n\n";
        return;
    }

    // Собираем прямую строку
    string s = p + "&" + t;

    // Собираем развернутую строку
    string p_r = p, t_r = t;
    reverse(p_r.begin(), p_r.end());
    reverse(t_r.begin(), t_r.end());
    string s_rev = p_r + "&" + t_r;

    vector<int> z = zfoo(s);
    vector<int> z_t = zfoo(s_rev);

    vector<int> ans;

    // Перебираем все возможные начальные позиции в тексте t (0-индексация)
    for (int i = 0; i <= t_l - p_l; i++)
    {
        // Индекс текущего символа текста в прямой строке s
        int idx1 = p_l + 1 + i;
        int match_front = z[idx1];

        // Если совпало полностью — это точное вхождение (окно ошибок = 0 <= k)
        if (match_front >= p_l)
        {
            ans.push_back(i + 1); // Сохраняем в 1-индексации
            continue;
        }

        // Индекс соответствующего символа в развернутой строке s_rev
        // Конец подстроки в t имеет индекс (i + p_l - 1).
        // В развернутой t_r этот символ сместится на позицию: t_l - 1 - (i + p_l - 1)
        int idx2 = p_l + 1 + (t_l - i - p_l);
        int match_back = z_t[idx2];

        // Первое несовпадение слева (в индексах образца от 0 до p_l - 1)
        int first_mismatch = match_front;

        // Последнее несовпадение (считая слева)
        int last_mismatch = p_l - 1 - match_back;

        // Размер окна, в которое гарантированно попадают ВСЕ несовпадения
        int window_size = last_mismatch - first_mismatch + 1;

        // Если все несовпадения влезают в окно размера k, то это неточное вхождение
        if (window_size <= k)
        {
            ans.push_back(i + 1); // Переводим в 1-индексацию
        }
    }

    // Выводим результат в соответствии с требованиями задачи
    cout << ans.size() << "\n";
    for (int i = 0; i < ans.size(); i++)
    {
        cout << ans[i] << (i == ans.size() - 1 ? "" : " ");
    }
    cout << "\n";
}

int32_t main()
{
    // Включаем супер-быстрый ввод-вывод для C++
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);

    solve();
    return 0;
}
