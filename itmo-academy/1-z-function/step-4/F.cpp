// Заданы две строки s и t. Выведите наиболее короткую их надстроку — такую строку r,
// которая содержит и s, и t в качестве подстрок.

// Входные данные
// В первой строке входных данных записано целое число q (1 ≤ q ≤ 10^5) — количество
// наборов входных данных в тесте.

// Каждый набор входных данных состоит из двух строк s и t. Длина строки s от 1 до 10^6
// символов, длина строки t от 1 до 10^6 символов. Строки s и t состоят исключительно
// из прописных и строчных букв латинского алфавита и цифр.

// Сумма длин строк s по всем q наборам входных данных в тесте не превосходит 10^6.
// Аналогично, сумма длин строк t по всем q наборам входных данных в тесте не превосходит 10^6.

// Выходные данные
// Для каждого набора входных данных выведите кратчайшую надстроку s и t. Если таких
// несколько, то выведите любую из них.

// ======================================================================
// Пример
// ======================================================================
// Входные данные
// ======================================================================
// 6
// abacaba
// ababa
// itmo
// university
// for
// codeforces
// ababab
// bababa
// x
// y
// itmo
// more
// ======================================================================
// Выходные данные
// ======================================================================
