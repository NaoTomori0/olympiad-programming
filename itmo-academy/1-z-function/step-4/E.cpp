// ЛОГИКА РЕШЕНИЯ ЗАДАЧИ "СТРАННАЯ ОПЕРАЦИЯ":
// Суть операции: Если мы выбираем число i (количество отрезаемых символов), строка s разделяется
//    на префикс длины i (кусок A) и суффикс длины n-i (кусок B). После операции кусок A разворачивается (A^R)
//    и приписывается в конец куска B. Таким образом, результирующая строка t должна иметь вид: t = B + A^R.
//    Отсюда получаем два жестких условия для целевой строки t:
//    - Ее начало (первые n-i символов) должно быть в точности равно суффиксу строки s (куску B).
//    - Ее конец (последние i символов) в перевернутом виде должен быть равен префиксу строки s (куску A).

// Оптимизация через Z-функцию: Чтобы не перебирать все варианты за O(n^2), мы проверяем эти два условия
//    одновременно за O(1) для каждого i с помощью двух склеек строк и Z-функции.

//    - Проверка суффикса B (Неравенство 1): Склеиваем строку str2 = t + "&" + s. В этой строке суффикс
//      строки s длины n-i начинается с индекса (n + 1 + i). Z-функция для этого индекса (z2[n + 1 + i])
//      показывает длину совпадения этой подстроки с началом всей строки str2 (то есть с началом строки t).
//      Нам нужно, чтобы совпадение было не меньше длины самого суффикса, то есть: z2[n + 1 + i] >= n - i.

//    - Проверка префикса A (Неравенство 2): Сначала полностью переворачиваем строку t (получаем t_rev).
//      При этом последние i символов строки t становятся первыми i символами строки t_rev. Теперь нам нужно
//      проверить, совпадают ли они с префиксом s. Склеиваем строку str1 = s + "&" + t_rev. В ней строка
//      t_rev начинается ровно с индекса (n + 1). Значение z1[n + 1] показывает, сколько первых символов
//      строки t_rev совпадают с началом строки s. Нам нужно совпадение длиной хотя бы i, то есть: z1[n + 1] >= i.

//  Финал: Посчитав обе Z-функции один раз, мы запускаем цикл по i от 0 до n. Первая итерация, где выполняются
//  оба неравенства одновременно, дает нам гарантированно минимальное и правильное значение i. Если цикл
//  завершается без совпадений, то сделать строки одинаковыми невозможно.

#include <bits/stdc++.h> // Подключает сразу все библиотеки C++
using namespace std;

#define int long long // Защита от переполнения int (из-за этого часто горят баллы)

std::vector<int> zfoo(std::string s)
{
    int n = s.length(); // длина строки всей
    std::vector<int> z(n, 0);
    int l = 0, r = 0;
    for (int i = 1; i < n; i++)
    {
        if (i <= r)
        {
            z[i] = min(r - i + 1, z[i - l]);
        }

        while (i + z[i] < n && s[z[i] + i] == s[z[i]])
        {
            ++z[i];
        }
        if (r < z[i] + i - 1)
        {
            l = i;
            r = z[i] + i - 1;
        }
    }
    return z;
}

