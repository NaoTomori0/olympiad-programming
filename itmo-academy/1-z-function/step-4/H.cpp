// H. Сумма длин различных подстрок
// ограничение по времени на тест2 секунды
// ограничение по памяти на тест512 мегабайт

// Решите эту задачу с использованием z-функции строки. Существует много способов
// решить её, но в качестве упражнения на использование z-функции попробуйте
// придумать и реализовать именно такое решение.

// Задана строка s. Выведите суммарную длину всевозможных различных подстрок этой строки.

// Входные данные
// Единственная строка входных данных содержит s — последовательность прописных и строчных
// латинских букв. Длина s не превышает 8000 символов.

// Выходные данные
// Выведите единственное целое число — суммарную длину всех различных подстрок.

// ======================================================================
// Примеры
// ======================================================================
// Входные данные
// ======================================================================
// BOBR
// ======================================================================
// Выходные данные
// ======================================================================
// 19

// ======================================================================
// Входные данные
// ======================================================================
// ABACABA
// ======================================================================
// Выходные данные
// ======================================================================
// 73
// ======================================================================

// Примечание
// Для первого примера все различные подстроки — это: B, O, R, BO, OB, BR, BOB, OBR, BOBR.
// Сумма их длин равна 19.
#include <bits/stdc++.h>
using namespace std;

#define int long long

// Стандартная функция вычисления Z-функции за O(N)
vector<int> z_function(const string &s)
{
    int n = s.length();
    vector<int> z(n, 0);
    int l = 0, r = 0;
    for (int i = 1; i < n; i++)
    {
        if (i <= r)
        {
            z[i] = min(r - i + 1, z[i - l]);
        }
        while (i + z[i] < n && s[z[i]] == s[i + z[i]])
        {
            z[i]++;
        }
        if (i + z[i] - 1 > r)
        {
            l = i;
            r = i + z[i] - 1;
        }
    }
    return z;
}

void solve()
{
    string s;
    if (!(cin >> s))
        return;

    int n = s.length();
    int total_length = 0;

    // Идем справа налево
    for (int i = n - 1; i >= 0; i--)
    {
        // Выделяем текущий суффикс s[i...n-1]
        string current_suffix = s.substr(i);

        // Считаем Z-функцию для этого суффикса
        vector<int> z = z_function(current_suffix);

        // Находим максимальное совпадение внутри суффикса
        int max_z = 0;
        for (int val : z)
        {
            max_z = max(max_z, val);
        }

        // Текущая полная длина суффикса
        int cur_len = n - i;

        // Уникальные подстроки имеют длины от (max_z + 1) до cur_len.
        // Нам нужно просуммировать все числа в этом диапазоне.
        if (cur_len > max_z)
        {
            int count = cur_len - max_z; // Количество новых уникальных подстрок
            int first = max_z + 1;       // Длина первой новой подстроки
            int last = cur_len;          // Длина последней новой подстроки

            // Формула суммы арифметической прогрессии
            total_length += (first + last) * count / 2;
        }
    }

    cout << total_length << "\n";
}

int32_t main()
{
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);

    solve();
    return 0;
}
