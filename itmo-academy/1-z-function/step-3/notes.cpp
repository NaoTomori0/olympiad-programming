/*
================================================================================
ШПАРГАЛКА ПО АЛГОРИТМУ: Z-ФУНКЦИЯ ЗА ЛИНЕЙНОЕ ВРЕМЯ O(N)
================================================================================

Что такое Z-функция?
-------------------
Z-функция строки S — это массив Z, где Z[i] равно длине наидлиннейшего общего
префикса между всей строкой S и её суффиксом, начинающимся с индекса i.
Простыми словами: Z[i] показывает, сколько букв, начиная с позиции i, в точности
совпадают с первыми буквами всей строки S. По условию задачи Z[0] всегда равен 0.

Как алгоритм работает за O(N) вместо O(N^2)?
--------------------------------------------
Вместо того чтобы для каждого индекса i заново сравнивать символы с самого начала
строки (что было бы долго), мы сохраняем границы самого правого совпадения,
которое мы встретили ранее. Эти границы обозначаются как [l...r].

Отрезок [l...r] — это наша "зона безопасности". Мы точно знаем, что подстрока
от индекса l до r полностью идентична началу строки (префиксу).

Внутри основного цикла есть 3 ключевых шага:

1. БЛОК ОПТИМИЗАЦИИ (if (i <= r))
   Если текущий индекс i находится внутри зоны безопасности [l...r], то символ S[i]
   соответствует символу S[i - l] в начале строки. Мы можем попытаться
   скопировать старый ответ: Z[i] = Z[i - l].
   НО! Мы не можем слепо верить старому ответу, если он уходит за правую границу r.
   Всё, что правее r — это неизведанная территория. Поэтому мы берем МИНИМУМ
   между старым ответом Z[i - l] и оставшимся расстоянием до конца зоны: (r - i + 1).

2. БЛОК НАИВНОГО РАСШИРЕНИЯ (while)
   После того как мы получили безопасный стартовый минимум для Z[i], мы пытаемся
   продлить совпадение дальше. Цикл проверяет:
   - (i + Z[i] < n) — не вышли ли мы за правый край всей строки?
   - (s[Z[i] + i] == s[Z[i]]) — равен ли следующий символ в хвосте (суффиксе)
     соответствующему символу в начале строки (префиксе)?
   Если условия верны, мы увеличиваем Z[i] на 1.

3. БЛОК ОБНОВЛЕНИЯ ГРАНИЦ (if (r < Z[i] + i - 1))
   Если текущее совпадение расширилось так далеко, что его правый конец
   (Z[i] + i - 1) вылез за пределы старой границы r, мы обновляем наше окно
   безопасности: теперь l становится равным i, а r сдвигается на самый край
   этого нового совпадения.

Благодаря этому окну [l...r] каждый символ строки проверяется циклом while
символьно очень редко, что обеспечивает суммарную скорость работы O(N).
================================================================================
*/

#include <bits/stdc++.h> // Подключает сразу все библиотеки C++
using namespace std;

#define int long long // Защита от переполнения int (из-за этого часто горят баллы)

std::vector<int> solve(std::string s)
{
    int n = s.length(); // длина всей строки
    std::vector<int> z(n, 0);
    int l = 0, r = 0;

    for (int i = 1; i < n; i++)
    {
        // Шаг 1: Используем уже посчитанные значения, если мы внутри границ [l...r]
        if (i <= r)
        {
            z[i] = min(r - i + 1, z[i - l]);
        }

        // Шаг 2: Пытаемся наивно расширить совпадение вправо
        while (i + z[i] < n && s[z[i] + i] == s[z[i]])
        {
            ++z[i];
        }

        // Шаг 3: Если продвинулись правее текущей границы r — сдвигаем окно [l...r]
        if (r < z[i] + i - 1)
        {
            l = i;
            r = z[i] + i - 1;
        }
    }
    return z;
}

int32_t main()
{
    // Включаем супер-быстрый ввод-вывод для C++
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);

    std::string s = "";
    if (std::cin >> s)
    {
        std::vector<int> res = solve(s);
        for (auto i = res.begin(); i != res.end(); i++)
        {
            std::cout << *i << " ";
        }
        std::cout << "\n";
    }

    return 0;
}
