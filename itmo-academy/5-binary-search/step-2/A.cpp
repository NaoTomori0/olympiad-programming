// A. Упаковка прямоугольников
// ограничение по времени на тест2 секунды
// ограничение по памяти на тест512 мегабайт

// Есть n прямоугольников одинакового размера: w в ширину и h в длину. Требуется найти
// квадрат минимального размера, в который можно упаковать данные прямоугольники.
// Прямоугольники при этом нельзя поворачивать.

// Входные данные
// Ввод содержит три целых числа: w, h, n (1 ≤ w, h, n ≤ 10^9).

// Выходные данные
// Выведите минимальную длину стороны квадрата, в который можно упаковать заданные
// прямоугольники.

// ======================================================================
// Пример
// ======================================================================
// Входные данные
// ======================================================================
// 2 3 10
// ======================================================================
// Выходные данные
// ======================================================================
// 9

// ======================================================================
// Иллюстрация к примеру
// ======================================================================
// Квадрат со стороной 9 вмещает прямоугольники 2×3 (ширина×высота) без поворота.
// Например, можно разместить 3 ряда по 4 прямоугольника (всего 12 мест, но нужно 10).
// На схеме ниже '#' — это один прямоугольник 2×3, точки — пустое место.

// +-----------------+
// |####..####..####.|  (ширина 9 = 2+2+2+... но 9 не делится на 2, поэтому
// |####..####..####.|   в ряду помещаются 4 прямоугольника по 2 = 8, остаётся 1)
// |####..####..####.|
// |####..####..####.|
// |####..####..####.|
// |####..####..####.|
// |####..####..####.|
// |####..####..####.|
// |####..####..####.|
// +-----------------+

// Пояснение: каждый прямоугольник имеет ширину 2 и высоту 3, поэтому в строке
// помещается floor(9/2)=4 прямоугольника, а в столбце floor(9/3)=3, всего 12,
// что достаточно для 10.
// ======================================================================

#include <bits/stdc++.h> // Подключает сразу все библиотеки C++
using namespace std;

#define int long long // Защита от переполнения int (из-за этого часто горят баллы)

bool good(int w, int h, int n, int m)
{
    return (m / w) * (m / h) >= n;
}

void solve()
{
    int w, h, n, l = 1, r = 1;
    cin >> w >> h >> n;

    while (!good(w, h, n, r))
    {
        r *= 2;
    }

    while (r > l + 1)
    {
        int m = (l + r) / 2;

        if (good(w, h, n, m))
            r = m;
        else
            l = m;
    }
    cout << r;
}

int32_t main()
{
    // Включаем супер-быстрый ввод-вывод для C++
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);

    solve();
    return 0;
}
