// D. Минимальный максимум на пути
// ограничение по времени на тест2 секунды
// ограничение по памяти на тест512 мегабайт

// Дорожная сеть состоит из n перекрёстков и m односторонних дорог, при этом каждая
// дорога ведёт из перекрёстка с меньшим номером в перекрёсток с большим номером.
// Каждой дороге соответствует некоторое число. Требуется найти путь из перекрёстка 1
// в перекрёсток n, состоящий из не более d рёбер, на котором максимум из чисел,
// соответствующих рёбрам, минимален.

// Входные данные
// Первая строка содержит целые числа n, m и d (2 ≤ n ≤ 10^5, 1 ≤ m, d ≤ 10^5).
// Следующие m строк содержат тройки чисел a_i, b_i, c_i (1 ≤ a_i < b_i ≤ n, 0 ≤ c_i ≤ 10^9),
// которые означают, что есть дорога, ведущая из перекрёстка a_i в перекрёсток b_i,
// которой соответствует число c_i. Для каждой пары перекрёстков существует не более
// одной дороги, которая их соединяет.

// Выходные данные
// В первой строке выведите число рёбер в выбранном пути k (k ≤ d). В следующей строке
// выведите k + 1 число — номера перекрёстков, которые посещает выбранный путь.

// Если не существует пути из перекрёстка 1 в перекрёсток n, состоящего из не более d
// рёбер, выведите одно число −1.

// ======================================================================
// Примеры
// ======================================================================
// Входные данные
// ======================================================================
// 4 5 2
// 1 2 5
// 2 3 3
// 1 3 7
// 2 4 6
// 3 4 4
// ======================================================================
// Выходные данные
// ======================================================================
// 2
// 1 2 4

// ======================================================================
// Входные данные
// ======================================================================
// 3 3 2
// 1 2 1
// 2 3 2
// 1 3 1
// ======================================================================
// Выходные данные
// ======================================================================
// 1
// 1 3

// ======================================================================
// Входные данные
// ======================================================================
// 3 2 1
// 1 2 1
// 2 3 1
// ======================================================================
// Выходные данные
// ======================================================================
// -1
// ======================================================================

#include <bits/stdc++.h> // Подключает сразу все библиотеки C++
using namespace std;

#define int long long // Защита от переполнения int (из-за этого часто горят баллы)

struct edge
{
    int to, weight;
};

bool check(int mid, int n, int d, vector<vector<edge>> &adj)
{
    vector<int> dist(n + 1, -1);
    queue<int> q;

    q.push(1);
    dist[1] = 0;

    while (!q.empty())
    {
        int u = q.front();
        q.pop();

        if (dist[u] >= d)
            continue; // Больше нельзя делать шаги

        for (auto &edge : adj[u])
        {
            if (edge.weight <= mid && dist[edge.to] == -1)
            {
                dist[edge.to] = dist[u] + 1;
                q.push(edge.to);
            }
        }
    }
    return dist[n] != -1; // Дошли ли мы до n?
}

void solve()
{
    int n, m, d, l = -1, r = 1e14;
    cin >> n >> m >> d;
    vector<vector<edge>> adj(n + 1);

    for (int i = 0; i < m; i++)
    {
        int u, v, c;
        cin >> u >> v >> c;
        adj[u].push_back({v, c});
    }

    while (r > l + 1)
    {
        int mid = (l + r) / 2;
        if (check(mid, n, d, adj))
            r = mid;
        else
            l = mid;
    }

    // Если r равно максимальному весу, проверяем, был ли путь вообще
    if (!check(r, n, d, adj))
    {
        cout << -1 << endl;
        return;
    }

    // Восстановление пути (BFS с сохранением родителей)
    vector<int> parent(n + 1, 0);
    vector<int> dist(n + 1, -1);
    queue<int> q;
    q.push(1);
    dist[1] = 0;
    while (!q.empty())
    {
        int u = q.front();
        q.pop();
        if (dist[u] >= d)
            continue;
        for (auto &e : adj[u])
        {
            if (e.weight <= r && dist[e.to] == -1)
            {
                dist[e.to] = dist[u] + 1;
                parent[e.to] = u;
                q.push(e.to);
            }
        }
    }

    // Собираем путь
    vector<int> path;
    for (int v = n; v != 0; v = parent[v])
        path.push_back(v);
    reverse(path.begin(), path.end());

    cout << path.size() - 1 << endl;
    for (int v : path)
        cout << v << " ";
}

int32_t main()
{
    // Включаем супер-быстрый ввод-вывод для C++
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);

    solve();
    return 0;
}
