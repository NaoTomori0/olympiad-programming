#include <bits/stdc++.h>
using namespace std;

#define int long long

void solve()
{
    int n, mx = 0;
    cin >> n;
    vector<int> a(n);
    for (auto &i : a)
    {
        cin >> i;
        mx = max(mx, i);
    }

    sort(a.begin(), a.end());

    int mxpw = mx + 1;
    string s = "";
    int l = 0, r = a.size() - 1, offset = 0;
    while (l <= r)
    {
        int dcnt, icnt;
        if (l < r)
        {
            dcnt = a[l] - offset;
            icnt = a[r] - a[r - 1];
        }
        else
        {
            dcnt = a[l] - offset;
            icnt = 1;
        }
        string tmp = "";
        for (int j = 0; j < icnt; j++)
            tmp.push_back('I');
        for (int j = 0; j < dcnt; j++)
            tmp.push_back('D');

        s = tmp + s;
        offset = a[l];
        l++;
        r--;
    }
    while (s.length() < mxpw)
        s = 'I' + s;

    list<pair<int, int>> res;
    for (int i = 0; i < mxpw; i++)
    {
        if (s[i] == 'D')
        {
            for (int j = 0; j < i; j++)
            {
                res.push_back({i + 1, j + 1});
            }
        }
    }
    cout << mxpw << ' ' << res.size() << '\n';
    for (auto i : res)
        cout << i.first << ' ' << i.second << '\n';
}

int32_t main()
{
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);
    int t;
    cin >> t;
    while (t--)
    {
        solve();
    }
    return 0;
}

