// G. Граф по множеству степеней
// ограничение по времени на тест5 секунд
// ограничение по памяти на тест256 мегабайт

// Вам дано множество степеней некоторого неориентированного графа. Постройте по
// заданному множеству неориентированный граф с минимальным количеством вершин.

// В графе не могут быть петли или кратные рёбра.

// Вершины графа нумеруются с единицы.

// Входные данные
// В первой строке находится целое число t (1 ≤ t ≤ 100) — количество наборов
// входных данных в тесте. Далее следуют t наборов входных данных. Перед каждым
// набором входных данных записана пустая строка.

// В первой строке каждого набора содержится одно целое число n (1 ≤ n ≤ 100) —
// размер множества степеней.

// В следующей строке записано множество из n различных чисел a1, a2, …, a_n
// (1 ≤ a_i ≤ 100) — степени вершин.

// Гарантируется, что по заданному множеству степеней можно построить граф.

// Выходные данные
// Для каждого набора входных данных выведите в отдельной строке количество вершин
// и количество рёбер в графе и сам граф в виде множества рёбер.

// Каждое ребро должно быть выведено в отдельной строке, как пара из двух чисел,
// записанных через пробел — номера вершин на концах ребра. В построенном графе
// множество степеней должно совпадать с заданным множеством степеней.

// Если существует несколько решений, выведите любое.

// ======================================================================
// Пример
// ======================================================================
// Входные данные
// ======================================================================
// 5

// 1
// 2

// 2
// 3 2

// 2
// 1 2

// 3
// 2 1 3

// 1
// 1
