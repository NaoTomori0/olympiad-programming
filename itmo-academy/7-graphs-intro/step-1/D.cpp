#include <bits/stdc++.h>
using namespace std;

#define int long long

void solve()
{
    int n, m, k;
    cin >> n >> m >> k;
    set<int> a;
    for (int i = 0; i < k; i++)
    {
        int x;
        cin >> x;
        a.insert(x);
    }
    bool ok = true;
    for (int i = 0; i < m; i++)
    {
        int u, v;
        cin >> u >> v;
        bool au = a.contains(u), av = a.contains(v);
        if ((!au && av) || (au && !av))
            ok = false;
    }
    if (!ok)
        cout << "NO\n";
    else
        cout << "YES\n";
}

int32_t main()
{
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);
    int t;
    cin >> t;
    while (t--)
    {
        solve();
    }
    return 0;
}
