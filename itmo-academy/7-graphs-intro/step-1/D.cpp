// Вам заданы неориентированный граф списком его рёбер и множество вершин. Проверьте,
// что заданные вершины образуют в точности одну или более компонент связности
// заданного графа.

// Иными словами, необходимо проверить, можно ли выбрать подмножество компонент
// связности так, что заданные вершины являются всеми вершинами этого подмножества
// компонент (и только ими).

// Входные данные
// В первой строке находится целое число t (1 ≤ t ≤ 10^5) — количество наборов
// входных данных в тесте. Далее следуют t наборов входных данных. Перед каждым
// набором входных данных записана пустая строка.

// В первой строке каждого набора содержатся три целых числа n, m и k
// (1 ≤ n ≤ 10^5, 0 ≤ m ≤ 10^5, 1 ≤ k ≤ 10^5), где n — количество вершин в графе,
// m — количество рёбер в графе, k — количество вершин в множестве.

// В следующей строке находится k целых чисел a1, a2, …, a_k (1 ≤ a_i ≤ n) —
// заданное множество вершин.

// В следующих m строках записаны рёбра, по одному ребру в строке. Каждое ребро
// характеризуется двумя целыми числами u и v (1 ≤ u, v ≤ n), где u — начало ребра,
// а v — конец ребра.

// В графе отсутствуют петли и кратные рёбра.

// Суммы n, m и k по всем наборам входных данных в одном тесте не превосходят 10^5.

// Выходные данные
// Для каждого набора входных данных в отдельной строке выведите:

// - «YES» — заданные вершины образуют в точности одну или более компоненту связности
//   заданного графа;
// - «NO» — в противном случае.

