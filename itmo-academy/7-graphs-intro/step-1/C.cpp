// 2 6
// 4 6
// ======================================================================
// Выходные данные
// ======================================================================
// path
// cycle
// simple path
// simple cycle
// none
// ======================================================================

#include <bits/stdc++.h>
using namespace std;

bool simple(vector<int> &a, int a_size, int start)
{
    set<int> st;
    for (int i = start; i < a_size; i++)
        st.insert(a[i]);
    return st.size() + start == a_size;
}

void solve()
{
    int n, m, k;
    cin >> n >> m >> k;
    vector<int> ak(k);
    for (auto &i : ak)
        cin >> i;
    vector<set<int>> g(n + 1);
    vector<pair<int, int>> ip(m);
    for (auto &i : ip)
    {
        cin >> i.first >> i.second;
        g[i.first].insert(i.second);
        g[i.second].insert(i.first);
    }

    for (int i = 0; i < k - 1; i++)
    {
        if (!g[ak[i]].contains(ak[i + 1]))
        {
            cout << "none\n";
            return;
        }
    }
    if (ak[0] == ak[k - 1])
    {
        if (simple(ak, k, 1))
        {
            cout << "simple cycle\n";
            return;
        }
        cout << "cycle\n";
        return;
    }
    if (simple(ak, k, 0))
    {
        cout << "simple path\n";
        return;
    }
    cout << "path\n";
}

int32_t main()
{
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);

    int t;
    cin >> t;
    while (t--)
    {
        solve();
    }

    return 0;
}