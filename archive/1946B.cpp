// Примечание
// В первом наборе входных данных нам выгодно взять пустой подотрезок массива дважды
// и вставить сумму пустого подотрезка (ноль) куда угодно, тогда сумма полученного
// массива будет (−4) + (−7) + 0 + 0 = −11, по модулю 10^9 + 7 это 999999996.

// Во втором наборе входных данных нам выгодно взять сумму всего массива трижды
// и разместить её где угодно в массиве, тогда одна из возможных последовательностей
// действий: [2, 2, 8] → [2, 2, 8, 12] → [2, 2, 8, 12, 24] → [2, 2, 8, 12, 24, 48],
// сумма конечного массива составляет 2 + 2 + 8 + 12 + 24 + 48 = 96.

// В четвёртом наборе входных данных нам выгодно взять подотрезок массива, состоящий
// из первых трёх чисел (т.е. состоящий из чисел 4, −2 и 8) и вставить его сумму
// в начало массива, тем самым получив массив [10, 4, −2, 8, −12, 9], сумма этого
// массива составляет 17.

// В седьмом наборе входных данных нам всегда будет выгодно брать пустой подотрезок
// массива. В таком случае сумма получившегося массива не будет отличаться от суммы
// исходного. Ответом будет сумма исходного массива, взятая по модулю — 42,
// так как (−6·(10^9 + 7) + 42 = −6000000000).

#include <bits/stdc++.h>
using namespace std;

#define int long long

const int MOD = 1e9 + 7;

void solve()
{
    int n, k;
    cin >> n >> k;
    vector<int> a(n), pref(n + 1, 0);
    for (int i = 0; i < n; i++)
    {
        cin >> a[i];
        pref[i + 1] = pref[i] + a[i];
    }
    int res = pref[n], loc_mx = 0; // *max_element(pref.begin(), pref.end());
    int l = 0, r = 0, s = 0;
    while (r < n)
    {
        s += a[r];
        while (l <= r && s < 0)
        {
            s -= a[l];
            l++;
        }
        loc_mx = max(loc_mx, s);
        r++;
    }

    while (k--)
    {
        res = ((res + loc_mx) % MOD + MOD) % MOD;
        loc_mx = ((loc_mx * 2) % MOD + MOD) % MOD;
    }
    cout << res << '\n';
}

int32_t main()
{
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);
    int t;
    cin >> t;
    while (t--)
    {
        solve();
    }
    return 0;
}
