// B. Максимальная сумма
// ограничение по времени на тест1 секунда
// ограничение по памяти на тест256 мегабайт

// У вас есть массив a из n целых чисел.

// Вы выполняете ровно k операций над ним. В одной операции вы выбираете любой
// непрерывный подотрезок массива a (возможно, пустой) и вставляете сумму этого
// подотрезка в любое место массива.

// Ваша задача — найти максимально возможную сумму массива после k таких операций.

// Поскольку это число может быть очень большим, выведите ответ по модулю 10^9 + 7.

// Напомним, что остаток от числа x по модулю p — это наименьшее неотрицательное y,
// такое что существует целое число q и x = p·q + y.

// Входные данные
// Каждый тест состоит из нескольких наборов входных данных. Первая строка содержит
// одно целое число t (1 ≤ t ≤ 10^4) — количество наборов входных данных. Затем следует
// описание наборов входных данных.

// Первая строка каждого набора входных данных содержит два целых числа n и k
// (1 ≤ n, k ≤ 2·10^5) — длина массива a и количество операций соответственно.

// Вторая строка каждого набора входных данных содержит n целых чисел a1, a2, …, a_n
// (−10^9 ≤ a_i ≤ 10^9) — сам массив a.

// Гарантируется, что сумма значений n и k для всех наборов входных данных
// не превосходит 2·10^5.

// Выходные данные
// Для каждого теста выведите одно целое число — максимальную сумму массива, которую
// можно получить после k операций, по модулю 10^9 + 7.

// ======================================================================
// Пример
// ======================================================================
// Входные данные
// ======================================================================
// 12
// 2 2
// -4 -7
// 3 3
// 2 2 8
