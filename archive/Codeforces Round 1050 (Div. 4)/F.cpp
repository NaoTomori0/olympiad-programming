// F. Гравити Фолз
// ограничение по времени на тест2 секунды
// ограничение по памяти на тест256 мегабайт

// У Фермера Джона есть n массивов a1, a2, …, a_n, которые могут иметь разные длины.
// Он будет укладывать массивы друг на друга, в результате чего получится сетка с n
// строками. Массивы выровнены по левому краю и могут быть уложены в любом порядке,
// в котором он пожелает.

// Затем произойдёт действие силы тяжести. Любая ячейка, которая не находится на
// нижнем ряду и не имеет элемента под собой, упадет на строку ниже. Этот процесс
// будет повторяться, пока не останется ячеек, которые удовлетворяют вышеуказанному
// условию.

// Для всех возможных способов, которыми ФД может уложить массивы, выведите
// лексикографически минимальный нижний ряд после действия силы тяжести.

// Входные данные
// Первая строка содержит t (1 ≤ t ≤ 1000) — количество наборов входных данных.

// Первая строка каждого набора входных данных содержит n (1 ≤ n ≤ 2·10^5).

// В следующих n строках первое целое число k_i (1 ≤ k ≤ 2·10^5) обозначает длину a_i.
// Затем следуют k_i целых чисел, разделённых пробелами, a_{i1}, a_{i2}, …, a_{i k_i}
// (1 ≤ a_{ij} ≤ 2·10^5).

// Гарантируется, что сумма n и сумма всех k_i по всем наборам входных данных
// не превышает 2·10^5.

// Выходные данные
// Для каждого набора входных данных выведите лексикографически минимальный нижний ряд
// в новой строке.

// ======================================================================
// Пример
// ======================================================================
// Входные данные
// ======================================================================
// 4
// 1
// 3 5 2 7
// 2
// 2 2 9
// 3 3 1 4
// 3
// 1 5
// 2 5 1
// 2 5 2
// 3
// 3 4 4 9
// 7 7 6 5 4 3 2 1
// 4 2 4 5 1
// ======================================================================
// Выходные данные
// ======================================================================
// 5 2 7
// 2 9 4
// 5 1
// 2 4 5 1 3 2 1
// ======================================================================
#include <bits/stdc++.h>

using namespace std;

// Функция для обновления максимума
template <class T>
bool update_max(T &a, const T &b)
{
    if (a < b)
    {
        a = b;
        return true;
    }
    return false;
}

void solve()
{
    int n;
    cin >> n;
    vector<vector<int>> g(n);
    vector<vector<int>> relevant;
    int max_k = 0;

    // Считываем массивы и заполняем структуру, показывающую,
    // какие массивы есть на каждой глубине j.
    for (int i = 0; i < n; ++i)
    {
        int k;
        cin >> k;
        g[i].resize(k);
        update_max(max_k, k);
        for (int j = 0; j < k; ++j)
        {
            cin >> g[i][j];
            if ((int)relevant.size() == j)
            {
                relevant.push_back({});
            }
            relevant[j].push_back(i);
        }
    }

    // lex_min[i] хранит индекс массива, который лучше всего приклеить на позиции i.
    // rank[j] хранит относительный порядок суффикса j-го массива.
    vector<int> lex_min(max_k);
    vector<int> rank(n, -1);

    // Идем справа налево (от конца массива к началу)
    for (int i = max_k - 1; i >= 0; --i)
    {
        struct Element
        {
            int val, rk, id;
            bool operator<(const Element &other) const
            {
                if (val != other.val)
                    return val < other.val;
                return rk < other.rk;
            }
        };

        vector<Element> cur;
        for (int j : relevant[i])
        {
            cur.push_back({g[j][i], rank[j], j});
        }
        sort(cur.begin(), cur.end());

        lex_min[i] = cur[0].id;

        int rk = 0;
        for (size_t j = 0; j < cur.size(); ++j)
        {
            if (j > 0 && (cur[j].val != cur[j - 1].val || cur[j].rk != cur[j - 1].rk))
            {
                rk++;
            }
            rank[cur[j].id] = rk;
        }
    }

    // Собираем ответ
    vector<int> ans;
    while ((int)ans.size() < max_k)
    {
        int tmp = (int)ans.size();
        const vector<int> &v = g[lex_min[tmp]];
        for (size_t i = tmp; i < v.size(); ++i)
        {
            ans.push_back(v[i]);
        }
    }

    // Вывод результата
    for (size_t i = 0; i < ans.size(); ++i)
    {
        cout << ans[i] << (i == ans.size() - 1 ? "" : " ");
    }
    cout << "\n";
}

int main()
{
    // Ускорение ввода-вывода
    ios::sync_with_stdio(false);
    cin.tie(nullptr);

    int t;
    cin >> t;
    while (t--)
    {
        solve();
    }
    return 0;
}