// - и так далее …

// Обратите внимание, что вы всегда начинаете с кружки горячей воды.

// Бочка изначально пустая. Необходимо налить хотя бы одну кружку в бочку. Температура
// воды в бочке равна средней температуре вылитых кружек.

// Вы хотите получить воду температуры как можно ближе к t. То есть если температура
// воды в бочке равна t_b, то абсолютная разность t_b и t (|t_b − t|) должна быть
// минимально возможна.

// Сколько кружек необходимо налить в бочку, чтобы температура стала как можно ближе
