// то выведите наименьший из них.

// Входные данные
// В первой строке записано одно целое число T (1 ≤ T ≤ 3·10^4) — количество наборов
// входных данных.

// В каждой из следующих T строк записаны по три целых числа h, c и t
// (1 ≤ c < h ≤ 10^6; c ≤ t ≤ h) — температура горячей воды, температура холодной воды
// и желаемая температура в бочке.

// Выходные данные
// На каждый набор входных данных выведите одно положительное целое число — минимальное
// количество кружек, которое необходимо вылить в бочку, чтобы получить температуру,
// как можно более близкую к t.

// ======================================================================
// Пример
// ======================================================================
// Входные данные
// ======================================================================
// 3
// 30 10 20
// 41 15 30
// 18 13 18
// ======================================================================
// Выходные данные
// ======================================================================
// 2
// 7
// 1
// ======================================================================

// Примечание
// В первом наборе входных данных температура после 2 налитых кружек: 1 горячей
// и 1 холодной — равна 20. И это самое близкое возможное значение.

// Во втором наборе температура после 7 налитых кружек: 4 горячих и 3 холодных —
// примерно 29.857. Если наливать больше воды, то температура не станет ближе к t.

// В третьем наборе температура после 1 налитой кружки: 1 горячей — равна 18.
// Это совпадает с t.

