// D. Падающий бетон
// ограничение по времени на тест2 секунды
// ограничение по памяти на тест256 мегабайт

// Вихаан ремонтирует дорогу, состоящую из n участков. Высота i-го участка равна a_i.

// У него есть погрузчик, который может перемещать участки дороги. За одну операцию
// Вихаан выбирает два индекса i и j (1 ≤ i < j ≤ n), поднимает j-й участок и переносит
// его назад в позицию i.

// Пока участок переносится назад, с него падает по одной единице бетона на каждый
// участок, над которым он проходит. Затем перенесённый участок вставляется в позицию i.

// Формально, подмассив
// [a_i, a_{i+1}, …, a_{j−1}, a_j]
// заменяется на
// [a_j − (j − i), a_{i+1}, a_{i+1} + 1, …, a_{j−1} + 1].

// Часть дороги называется ровной, если это непрерывный отрезок участков с одинаковой
// высотой.

// Вихаан может выполнить любое количество операций, возможно, ноль.

// Найдите максимальную возможную длину ровной части дороги.

// Входные данные
// Первая строка содержит целое число t (1 ≤ t ≤ 10^4) — количество наборов входных данных.

// Первая строка каждого набора входных данных содержит целое число n (1 ≤ n ≤ 2·10^5) —
// количество участков дороги.

// Вторая строка содержит n целых чисел a1, a2, …, a_n (n ≤ a_i ≤ 10^9) — начальные
// высоты участков.

// Гарантируется, что сумма n по всем наборам входных данных не превосходит 2·10^5.

// Можно показать, что при данных ограничениях высота каждого участка остаётся
// положительной после любой последовательности операций.

// Выходные данные
// Для каждого набора входных данных выведите одно целое число — максимальную возможную
// длину ровной части дороги.

// ======================================================================
// Пример
// ======================================================================
// Входные данные
// ======================================================================
// 8
// 5
// 5 5 5 9 8
// 6
// 6 6 6 6 6 6
// 5
// 5 6 7 8 9
// 5
// 9 7 12 10 12
// 4
// 4 7 5 8
// 7
// 14 9 14 12 8 11 12
// 5
// 1000000000 1000000000 1000000000 1000000000 1000000000
// 8
// 8 8 12 8 14 10 15 13
// ======================================================================
// Выходные данные
// ======================================================================
// 4
// 6
// 1
// 5
// 4
// 2
// 5
// 6
// ======================================================================

// Примечание
// В первом наборе входных данных Вихаан может переместить участок с позиции 4 в позицию 1:

// [5, 5, 5, 9, 8] → [6, 6, 6, 6, 8].

// Таким образом, можно создать ровную часть длины 4.

// В четвёртом наборе входных данных Вихаан может выполнить следующие операции:

// - Переместить участок с позиции 3 в позицию 1:
//   [9, 7, 12, 10, 12] → [10, 10, 8, 10, 12].
// - Переместить участок с позиции 4 в позицию 3:
//   [10, 10, 8, 10, 12] → [10, 10, 9, 9, 12].
// - Переместить участок с позиции 5 в позицию 3:
//   [10, 10, 9, 9, 12] → [10, 10, 10, 10, 10].

// Таким образом, всю дорогу можно сделать ровной.

// В пятом наборе входных данных Вихаан может сначала переместить участок с позиции 2
// в позицию 1:

// [4, 7, 5, 8] → [6, 5, 5, 8].

// Затем он может переместить участок с позиции 4 в позицию 2:

// [6, 5, 5, 8] → [6, 6, 6, 6].

// Таким образом, всю дорогу можно сделать ровной.

#include <bits/stdc++.h>
using namespace std;

#define int long long

void solve()
{
    int n;
    cin >> n;
    vector<int> a(n), b(n);
    for (int i = 0; i < n; i++)
    {
        cin >> a[i];
        b[i] = a[i] - (i + 1);
    }
    sort(b.begin(), b.end());
    b.erase(unique(b.begin(), b.end()), b.end());

    int res = 1;
    int loc = 1;
    for (int i = 1; i < b.size(); i++)
    {
        if (b[i] == b[i - 1] + 1)
            loc++;
        else
        {
            res = max(res, loc);
            loc = 1;
        }
    }
    cout << max(res, loc) << '\n';
}

int32_t main()
{
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);
    int t;
    cin >> t;
    while (t--)
        solve();
    return 0;
}
