// Примечание
// В первом примере из условия нужно купить 8 упаковок апельсинового сока и 7 упаковок
// яблочного сока. Одна упаковка стоит 80 рублей, а коробка из 5 упаковок — 370 рублей.
// На 1110 рублей можно купить 3 коробки сока, например, две коробки апельсинового
// и одну коробку яблочного. Останется 1400 − 3·370 = 290 рублей: 240 рублей хватит
// на 3 упаковки яблочного сока (или 2 упаковки яблочного и 1 — апельсинового),
// 50 рублей останется. Условия будут выполнены, всего будет приобретено 3·5 + 3 = 18
// упаковок сока.

// Во втором примере на 1200 рублей можно приобрести 5 коробок сока по 225 рублей.
// Если взять три коробки апельсинового сока и две коробки яблочного, то условия
// будут выполнены. Останется 1200 − 5·225 = 75 рублей, на которые ничего нельзя купить.

// В третьем примере на 1100 рублей можно купить 2 коробки сока по 375 рублей:
// коробку апельсинового и коробку яблочного. Останется 1100 − 2·375 = 350 рублей,
// на которые нужно купить ещё три упаковки апельсинового и две упаковки яблочного
// сока. При стоимости упаковки в 80 рублей это сделать нельзя.