// ограничение по памяти на тест256 мегабайт

// Дана последовательность целых чисел a длины n.

// Назовём последовательность красивой, если она имеет вид ряда блоков, каждый из которых
// начинается со своей длины, то есть сначала идёт длина блока, а потом его элементы.
// Например, последовательности [3, 3, 4, 5, 2, 6, 1] и [1, 8, 4, 5, 2, 6, 1] являются
// красивыми (разные блоки покрашены разными цветами), а [1], [1, 4, 3], [3, 2, 1] — нет.

// За одну операцию вы можете удалить из последовательности любой элемент. Какое
// минимальное количество операций нужно сделать, чтобы данная последовательность
// стала красивой.

// Входные данные
// В первой строке входных данных содержится одно целое число t (1 ≤ t ≤ 10^4) —
// количество наборов входных данных в тесте. Далее следуют описания наборов.

// Первая строка каждого набора содержит одно целое число n (1 ≤ n ≤ 2·10^5) —
// длину последовательности a.

// Вторая строка каждого набора содержит n целых чисел a1, a2, …, a_n (1 ≤ a_i ≤ 10^6) —
// элементы последовательности a.

// Гарантируется, что сумма значений n по всем наборам входных данных не превосходит 2·10^5.

// Выходные данные
// Для каждого набора входных данных выведите одно число — минимальное количество
// удалений, которые нужно совершить, чтобы последовательность a стала красивой.

// ======================================================================
// Пример
// ======================================================================
// Входные данные
// ======================================================================
// 7
// 7
