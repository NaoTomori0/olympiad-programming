// 5
// 4 5 5 1 5
// ======================================================================
// Выходные данные
// ======================================================================
// 0
// 4
// 1
// 1
// 2
// 1
// 0
// ======================================================================

// Примечание
// В первом наборе входных данных примера данная последовательность уже является
// красивой, как и показано в условии.

// Во втором наборе входных данных примера можно сделать последовательность красивой
