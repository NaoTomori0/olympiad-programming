// Примечание
// На картинке изображён первый тестовый пример (в оригинале).

#include <bits/stdc++.h>
using namespace std;

#define int long long

void solve()
{
    int n;
    cin >> n;
    vector<int> a(n);
    for (auto &i : a)
        cin >> i;

    int q;
    cin >> q;
    int last_t = 0;
    while (q--)
    {
        int w, h;
        cin >> w >> h;
        int ans = max(a[w - 1], last_t);
        cout << ans << '\n';
        last_t = ans + h;
    }

    // for (auto &i : pref)
    //     cout << i.first << ' ' << i.second << '\n';
}

int32_t main()
{
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);

    solve();
    return 0;
}
