#include <bits/stdc++.h>
using namespace std;

#define int long long

void solve()
{
    int n;
    cin >> n;
    vector<string> a(n);
    for (auto &i : a)
        cin >> i;
    vector<vector<int>> gra(26);
    vector<int> p(26, 0);
    for (int i = 0; i < n - 1; i++)
    {
        int j = 0;
        while (j < a[i].size() && j < a[i + 1].size() && a[i][j] == a[i + 1][j])
            j++;

        if (j == min(a[i].size(), a[i + 1].size()))
        {
            if (a[i].size() > a[i + 1].size())
            {
                cout << "Impossible";
                return;
            }
            continue;
        }

        gra[a[i][j] - 'a'].push_back(a[i + 1][j] - 'a');
        p[a[i + 1][j] - 'a']++;
    }

    queue<int> q;
    vector<int> res;
    for (int i = 0; i < 26; i++)
        if (!p[i])
        {
            q.push(i);
            res.push_back(i);
        }

    while (!q.empty())
    {
        int cur = q.front();
        q.pop();

        for (auto &i : gra[cur])
        {
            p[i]--;
            if (!p[i])
            {
                res.push_back(i);
                q.push(i);
            }
        }
    }
    if (res.size() != 26)
    {
        cout << "Impossible";
        return;
    }
    for (auto &i : res)
        cout << char('a' + i);
}

int32_t main()
{
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);

    solve();
    return 0;
}
