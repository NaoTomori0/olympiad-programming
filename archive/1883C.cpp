// Примечание
// В первом наборе входных данных нужно два раза выбрать индекс i = 2. После этого
// массив будет равен a = [7, 5]. Произведение всех чисел массива равно 35.

// В четвёртом наборе входных данных произведение чисел массива равно 120, что уже
// делится на 5, поэтому не нужно применять операции.

// В восьмом наборе входных данных можно сделать две операции, выбрав i = 2 и i = 3
// в любом порядке. После этого массив будет равен a = [1, 6, 10]. Произведение чисел
// массива равно 60.

#include <bits/stdc++.h>
using namespace std;

#define int long long

void solve()
{
    int n, k;
    cin >> n >> k;
    int min_r = k, cnt2 = 0;
    for (int i = 0; i < n; i++)
    {
        int x;
        cin >> x;
        cnt2 += x % 2 == 0;
        min_r = min(min_r, (x % k ? k - x % k : 0));
    }
    cout << (k == 4 ? max(0LL, min(2 - cnt2, min_r)) : min_r) << '\n';
}

int32_t main()
{
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);
    int t;
    cin >> t;
    while (t--)
        solve();
    return 0;
}
