// Вам дан массив целых чисел a1, a2, …, a_n и число k (2 ≤ k ≤ 5). За одну операцию
// вы можете сделать следующее:

// - Выбрать индекс 1 ≤ i ≤ n,
// - Сделать a_i = a_i + 1.

// Найдите наименьшее количество операций, которые нужно сделать, чтобы произведение
// всех чисел массива a1 · a2 · … · a_n делилось на k.

// Входные данные
// Каждый тест состоит из нескольких наборов входных данных. Первая строка содержит
// единственное целое число t (1 ≤ t ≤ 10^4) — количество наборов входных данных.
// Далее следует их описание.

// Первая строка каждого набора входных данных содержит два целых числа n и k
// (2 ≤ n ≤ 10^5, 2 ≤ k ≤ 5) — размер массива a и число k.

// Вторая строка каждого набора входных данных содержит n целых чисел
// a1, a2, …, a_n (1 ≤ a_i ≤ 10).

// Гарантируется, что сумма n по всем наборам входных данных не превосходит 2·10^5.

// Выходные данные
// Для каждого набора входных данных выведите наименьшее количество операций, которое
// нужно сделать, чтобы произведение всех чисел массива делилось на k.

