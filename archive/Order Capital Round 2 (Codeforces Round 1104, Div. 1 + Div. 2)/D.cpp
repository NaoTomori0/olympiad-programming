// Бинарная строка — это строка, состоящая только из символов 0 и 1. Символы 0 и 1
// называются противоположными значениями.

// Рассмотрим бинарную строку t. Пусть |t| — длина строки t. При |t| ≥ 2 для каждого
// 1 ≤ i < |t| символы t_i и t_{i+1} являются соседними.

// Бинарная строка t называется красивой, если её можно свести к строке длины ровно 1,
// применив следующую операцию любое количество раз, возможно ноль:

// - Выбрать два одинаковых соседних символа, удалить их оба и вставить на их место
//   один символ с противоположным значением.

// Например, строка 10001 может стать 1101 заменой соседней пары 00 на 1. Затем она
// может стать 001, затем 11, и наконец 0. Следовательно, 10001 является красивой.

// С другой стороны, 111 не является красивой. После одной операции она становится 01,
// и тогда никакая операция не может быть применена.

// Вам дана бинарная строка s. Подсчитайте количество непустых подстрок* строки s,
// которые являются красивыми.

// * Строка a является подстрокой строки b, если a может быть получена из b удалением
// нескольких (возможно, ни одного или всех) символов с начала и нескольких (возможно,
// ни одного или всех) символов с конца.

// Входные данные
// Каждый тест состоит из нескольких наборов входных данных. В первой строке находится
// одно целое число t (1 ≤ t ≤ 10^4) — количество наборов входных данных. Далее следует
// описание наборов входных данных.

// Первая строка каждого набора входных данных содержит целое число n (1 ≤ n ≤ 10^6) —
// длину строки s.

// Вторая строка каждого набора входных данных содержит бинарную строку s длины n.

// Гарантируется, что сумма значений n по всем наборам входных данных не превосходит 10^6.

// Выходные данные
// Для каждого набора входных данных выведите единственное целое число — количество
// красивых подстрок строки s.

// ======================================================================
// Пример
