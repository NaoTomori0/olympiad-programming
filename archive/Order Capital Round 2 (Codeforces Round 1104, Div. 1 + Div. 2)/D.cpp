// Примечание
// В первом наборе входных данных единственная непустая подстрока — 0, которая уже
// является бинарной строкой длины 1. Следовательно, она является красивой.

// Во втором наборе входных данных красивыми подстроками являются 0 и 1. Подстрока 01
// не является красивой, так как её два символа не равны, поэтому никакая операция
// не может быть применена.

// В третьем наборе входных данных красивыми подстроками являются:

