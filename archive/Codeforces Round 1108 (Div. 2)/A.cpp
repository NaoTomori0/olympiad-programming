// A. farmpiggie и сумма подмножеств
// ограничение по времени на тест1 секунда
// ограничение по памяти на тест256 мегабайт

// Для перестановки* p чётной длины вы можете выполнить следующий процесс:

// - Инициализировать счётчик c = 0.
// - Для каждого i от 1 до n либо прибавить i·p_i к c, либо вычесть i·p_i из c,
//   либо ничего не делать.
// - Пусть итоговое значение счётчика равно c_final.

// Формально, для каждого i ∈ {1, …, n} рассмотрим множество S_i = {−i·p_i, 0, i·p_i}
// и выберем некоторое x_i ∈ S_i. Положим c_final = ∑_{i=1}^{n} x_i.

// Дано одно чётное целое число n. Найдите любую перестановку длины n такую,
// что независимо от выбранных операций итоговое значение c_final не будет равно 1.

// * Перестановкой длины n является массив, состоящий из n различных целых чисел
// от 1 до n в произвольном порядке. Например, [2, 3, 1, 5, 4] — перестановка,
// но [1, 2, 2] не перестановка (2 встречается дважды) и [1, 3, 4] тоже не перестановка
// (n = 3, но в массиве встречается 4).

// Входные данные
// Каждый тест состоит из нескольких наборов входных данных. В первой строке находится
// одно целое число t (1 ≤ t ≤ 25) — количество наборов входных данных. Далее следует
// описание наборов входных данных.

// Первая и единственная строка каждого набора входных данных содержит одно чётное
// целое число n (2 ≤ n ≤ 50) — длину требуемой перестановки.

// Выходные данные
// Для каждого набора входных данных выведите n целых чисел p1, …, p_n (1 ≤ p_i ≤ n) —
// перестановку, удовлетворяющую условиям.

// Если решений несколько, выведите любое из них.

// ======================================================================
// Пример
// ======================================================================
// Входные данные
// ======================================================================
// 3
// 2
// 4
// 6
// ======================================================================
// Выходные данные
// ======================================================================
// 2 1
// 2 3 4 1
// 5 4 6 2 1 3
// ======================================================================

// Примечание
// В первом наборе входных данных перестановка, приведённая в выводе, равна [2, 1].
// Счётчик можно изменить следующими 9 способами:

// 0 → +2·1 → +0 → 2
// 0 → +0 → +1·2 → 2
// 0 → −2·1 → +0 → −2
// 0 → +0 → −1·2 → −2
// 0 → −2·1 → +1·2 → 0
// 0 → +2·1 → −1·2 → 0
// 0 → −2·1 → −1·2 → −4
// 0 → +2·1 → +1·2 → 4
// 0 → +0 → +0 → 0

// Ни одно из этих значений не равно 1, поэтому перестановка удовлетворяет условию.

// Можно показать, что перестановка, приведённая во втором наборе входных данных,
// удовлетворяет условию. Однако перестановка [1, 2, 3, 4] не удовлетворяла бы условию,
// поскольку последовательность 0 → +1·1 → +0 → +0 → +0 приводит к c = 1 в конце.

#include <bits/stdc++.h>
using namespace std;

#define int long long

void solve()
{
    int n;
    cin >> n;
    for (int i = 0; i < n; i++)
    {
        if (i % 2 == 0)
            cout << i + 2 << ' ';
        else
            cout << i << ' ';
    }
    cout << "\n";
}

int32_t main()
{
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);
    int t;
    cin >> t;
    while (t--)
    {
        solve();
    }
    return 0;
}
