// ограничение по памяти на тест256 мегабайт

// Вы играете в свою любимую ритм-игру, osu!mania. Макет вашей битмапы состоит из n
// строк и 4 столбцов. Поскольку ноты внизу ближе, вы будете обрабатывать самую нижнюю
// строку первой, а самую верхнюю строку последней. Каждая строка будет содержать ровно
// одну ноту, представленную как '#'.

// Для каждой ноты 1,2,…,n, в порядке обработки, выведите столбец, в котором появляется нота.

// Входные данные
// Первая строка содержит t (1 ≤ t ≤ 100) — количество наборов входных данных.

// Для каждого набора входных данных первая строка содержит n (1 ≤ n ≤ 500) — количество
// строк битмапы.

// Следующие n строк содержат 4 символа. i-я строка представляет собой i-ю строку битмапы
// сверху. Гарантируется, что символы являются либо '.' либо '#', и ровно один из символов
// является '#'.

// Гарантируется, что сумма n по всем наборам входных данных не превышает 500.

// Выходные данные
// Для каждого набора входных данных выведите n целых чисел в новой строке — номер столбца,
// в котором появляется i-я в порядке обработки нота для всех i от 1 до n.

// ======================================================================
// Пример
// ======================================================================
// Входные данные
// ======================================================================
// 1
// 3
// ..#.
// #...
// ...#
// ======================================================================
// Выходные данные
// ======================================================================
// 4 1 3
// ======================================================================

// (Пояснение: строки сверху вниз: первая "..#." (нота в столбце 3), вторая "#..." (столбец 1),
// третья "...#" (столбец 4). Обработка снизу вверх: сначала третья строка (столбец 4),
// затем вторая (столбец 1), затем первая (столбец 3). Ответ: 4 1 3.)

#include <bits/stdc++.h> // Подключает сразу все библиотеки C++
using namespace std;

#define int long long // Защита от переполнения int (из-за этого часто горят баллы)

vector<int> solve()
{
    int n;
    cin >> n;
    vector<int> result;
    for (int i = 0; i < n; i++)
    {
        string tmp;
        cin >> tmp;
        result.insert(result.begin(), tmp.find('#') + 1);
    }

    return result;
}

int32_t main()
{
    // Включаем супер-быстрый ввод-вывод для C++
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);

    int n;
    cin >> n;
    while (n--)
    {
        vector<int> res = solve();
        for (auto i = res.begin(); i != res.end(); ++i)
        {
            cout << *i << " ";
        }
        cout << "\n";
    }

    return 0;
}
