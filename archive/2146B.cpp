// Вам даны n множеств S1, S2, …, S_n, где каждый элемент множества — это целое число
// от 1 до m.

// Вы хотите выбрать некоторые из множеств (возможно, ни одно или все), так чтобы
// каждое целое число от 1 до m было включено в по крайней мере одно из выбранных
// множеств.

// Вам нужно определить, существуют ли по крайней мере три способа выбрать множества.

// Входные данные
// Каждый тест состоит из нескольких наборов входных данных. В первой строке находится
// одно целое число t (1 ≤ t ≤ 10^4) — количество наборов входных данных. Далее следует
// описание наборов входных данных.

// Первая строка каждого набора входных данных содержит два целых числа n и m
// (2 ≤ n ≤ 5·10^4, 1 ≤ m ≤ 10^5) — количество множеств и верхняя граница целых чисел
// в множествах.

// Затем следуют n строк, в i-й строке сначала содержится целое число l_i
// (1 ≤ l_i ≤ m) — размер множества S_i.

// Затем следуют l_i целых чисел S_{i,1}, S_{i,2}, …, S_{i,l_i} в той же строке
// (1 ≤ S_{i,1} < S_{i,2} < … < S_{i,l_i} ≤ m) — элементы множества S_i.

// Обозначим L = ∑_{i=1}^{n} l_i. Гарантируется, что:

// - Сумма n по всем наборам входных данных не превосходит 5·10^4;
// - Сумма m по всем наборам входных данных не превосходит 10^5;
// - Сумма L по всем наборам входных данных не превосходит 2·10^5.

// Выходные данные
// Для каждого набора входных данных выведите «YES», если существуют по крайней мере
// три способа выбрать множества. В противном случае выведите «NO».

// Вы можете выводить каждую букву в любом регистре (строчную или заглавную). Например,
// строки «yEs», «yes», «Yes» и «YES» будут распознаны как положительные ответы.

