// Примечание
// В первом наборе входных данных существует 5 ≥ 3 возможных способов выбрать множества:

// - S1 — оба числа 1 и 2 включены в S1;
// - S1 и S2 — 1 включено в S1 и S2, а 2 включено в S1;
// - S1 и S3 — 1 включено в S1, а 2 включено в S1 и S3;
// - S2 и S3 — 1 включено в S2, а 2 включено в S3;
// - S1, S2 и S3 — 1 включено в S1 и S2, а 2 включено в S1 и S3.

// Обратите внимание, что выбирать только S2 недопустимо, так как 2 не включено в S2.

// Во втором наборе входных данных единственный способ — выбрать все множества.

// В третьем наборе входных данных число 5 не встречается ни в одном из множеств,
// поэтому нет способа выбрать множества.

// В четвёртом наборе входных данных выбор любого непустого набора множеств допустим,
// поэтому количество способов равно 2^5 − 1 = 31 ≥ 3.

#include <bits/stdc++.h>
using namespace std;

#define int long long

void solve()
{
    int n, m;
    cin >> n >> m;
    vector<int> a(m, 0);
    vector<vector<int>> v(n);
    int t = 0;
    for (int i = 0; i < n; i++)
    {
        int x;
        cin >> x;
        for (int j = 0; j < x; j++)
        {
            int y;
            cin >> y;
            t += !a[--y];
            a[y]++;
            v[i].push_back(y);
        }
    }

    int ans = t == m;
    for (int i = 0; i < n; i++)
    {
        for (auto &x : v[i])
        {
            a[x]--;
            t -= !a[x];
        }
        ans += t == m;
        for (auto &x : v[i])
        {
            t += !a[x];
            a[x]++;
        }
    }
    cout << (ans >= 3 ? "YES\n" : "NO\n");
}

int32_t main()
{
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);
    int t;
    cin >> t;
    while (t--)
    {
        solve();
    }
    return 0;
}
