//   монет, тратит дополнительно 6 серебряных монет.
// - Второй физик, x = 6 серебряных монет: компания выплачивает 0, экономит 6
//   серебряных монет.

// Если же будет назначена премия в размере 7 серебряных монет для обоих астрофизиков,
