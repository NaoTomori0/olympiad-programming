// A. Разрушитель
// ограничение по времени на тест1 секунда
// ограничение по памяти на тест256 мегабайт

// Джон — ведущий программист на эсминце, принадлежащем космическому флоту Конфедерации
// независимых операционных систем. Одна из его задач — проверять, не были ли повреждены
// электронные мозги роботов во время сражений.

// Стандартный тест — приказать роботам сформировать один или несколько рядов, в каждом
// ряду роботы должны стоять друг за другом. После этого каждый робот доложит, сколько
// роботов стоит перед ним в его ряду.

// Пример расположения роботов (начало рядов слева). Роботы докладывают числа, указанные
// над ними.

// i-й робот доложил число l_i. К сожалению, Джон не знает, в каком ряду стоит каждый
// из роботов, и не может проверить доложенные числа. Определите, существует ли
// расположение роботов такое, что все доложенные числа корректны, или такого
// расположения не существует.

// Входные данные
// Каждый тест состоит из нескольких наборов входных данных. В первой строке находится
// одно целое число t (1 ≤ t ≤ 100) — количество наборов входных данных. Далее следует
// описание наборов входных данных.

// Первая строка каждого набора входных данных содержит одно число n (1 ≤ n ≤ 100) —
// количество роботов.

// Вторая строка каждого набора входных данных содержит n целых чисел l1, l2, …, l_n
// (0 ≤ l_i < 100), где l_i равно количеству роботов перед i-м роботом.

// Гарантируется, что сумма значений n по всем наборам входных данных не превосходит 200.

// Выходные данные
// Для каждого набора входных данных выведите «YES», если существует расстановка
// роботов, соответствующая заявлениям роботов. В противном случае выведите «NO».

// Вы можете выводить каждую букву в любом регистре (строчную или заглавную). Например,
// строки «yEs», «yes», «Yes» и «YES» будут приняты как положительный ответ.

// ======================================================================
// Пример
// ======================================================================
// Входные данные
// ======================================================================
// 5
// 6
// 0 1 2 0 1 0
// 9
// 0 0 0 0 1 1 1 2 2
// 3
// 0 0 2
// 1
// 99
// 5
// 0 1 2 3 4
// ======================================================================
// Выходные данные
// ======================================================================
// YES
// YES
// NO
// NO
// YES
// ======================================================================

// Примечание
// Пример расстановки, согласованной с утверждениями роботов из первого примера,
// приведён в условии (см. оригинальный рисунок).

// Пример расположения, согласованного с утверждениями роботов из второго примера,
// также показан в условии.

// В третьем наборе третий робот утверждает, что перед ним находятся две машины.
// В таком случае перед роботом, стоящим непосредственно перед ним, будет одна машина.
// Ни один робот не утверждает этого, поэтому нет правильного расположения.

#include <bits/stdc++.h>
using namespace std;

#define int long long

void solve()
{
    int n, max_el = 0;
    cin >> n;
    map<int, int> a;
    for (int i = 0; i < 201; i++)
        a.insert({i, 0});

    for (int i = 0; i < n; i++)
    {
        int x;
        cin >> x;
        a[x]++;
        max_el = max(max_el, x);
    }

    bool is_ok = true;
    for (int i = 0; i <= max_el; i++)
    {
        if (a[i] < a[i + 1] || a[i] == 0)
        {
            cout << "NO\n";
            return;
        }
    }
    cout << "YES\n";
}

int32_t main()
{
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);
    int t;
    cin >> t;
    while (t--)
    {
        solve();
    }

    return 0;
}
