// У Карен 4 вопроса.

// В первом вопросе она хочет узнать число приемлемых целочисленных температур между
// 92 и 94 градусами включительно. Таких 3: 92, 93 и 94 градуса являются приемлемыми.

// Во втором вопросе она хочет узнать число приемлемых целочисленных температур между
// 93 и 97 градусами включительно. Таких 3: 93, 94 и 97 градуса являются приемлемыми.

// В третьем вопросе она хочет узнать число приемлемых целочисленных температур между
// 95 и 96 градусами включительно. Таких нет.

// В последнем вопросе она хочет узнать число приемлемых целочисленных температур между
// 90 и 100 градусами включительно. Таких 4: 92, 93, 94 и 97 градуса являются приемлемыми.

// Во втором примере Карен знает 2 рецепта.

// Первый из них, «wikiHow to make Cold Brew Coffee», рекомендует заваривать кофе при
