// Карен — поклонница кофе — хочет узнать оптимальную температуру заваривания кофе.
// Для этого она потратила некоторое время на чтение нескольких книг рецептов, в том
// числе общепризнанную книгу «Искусство ковфефе».

// Карен знает n рецептов кофе. i-й из них рекомендует заваривать кофе при температуре
// от l_i до r_i градусов включительно.

// Карен считает, что температура является приемлемой, если хотя бы k рецептов
// рекомендуют её.

// Карен очень непостоянная, поэтому у неё есть q вопросов. В каждом вопросе она хочет
// заварить кофе с целочисленной температурой от a до b градусов включительно, и хочет
// узнать, сколько приемлемых целочисленных температур находятся в этом промежутке.

// Входные данные
// В первой строке содержится три целых числа n, k (1 ≤ k ≤ n ≤ 200000) и q
// (1 ≤ q ≤ 200000) — число рецептов, минимальное количество рецептов, необходимое
// для признания температуры приемлемой, и количество вопросов Карен соответственно.

// Следующие n строк описывают рецепты. А именно, i-я из этих строк содержит два целых
// числа l_i и r_i (1 ≤ l_i ≤ r_i ≤ 200000), означающих, что i-й рецепт рекомендует
// заваривать кофе с температурой между l_i и r_i градусами включительно.

// Следующие q строк описывают вопросы Карен. Каждая из этих строк содержит два целых
// числа a и b (1 ≤ a ≤ b ≤ 200000), означающих, что она хочет узнать число приемлемых
// целочисленных температур между a и b градусами включительно.

// Выходные данные
// Для каждого вопроса выведите одно целое число — число приемлемых целочисленных
// температур между a и b градусами включительно.

// ======================================================================
// Примеры
// ======================================================================
