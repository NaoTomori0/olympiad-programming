// D. Бермудский прямоугольник
// ограничение по времени на тест2 секунды
// ограничение по памяти на тест256 мегабайт

// Бобр плывёт по океану (да, он и не такое может). Здесь он с целью исследовать
// Бермудский Прямоугольник. Бобру он, конечно, не представляет никакой опасности,
// но интересен с научной точки зрения.

// В отличие от Бермудского Треугольника, про Бермудский Прямоугольник известно
// не так много. А именно, Бобр достоверно знает, что площадь прямоугольника равна S,
// его стороны целые, и левый нижний угол находится в точке (0, 0).

// Бобра интересует, сколько клеток из прямоугольника со сторонами x и y,
// у которого левый нижний угол находится в точке (0, 0), могут находиться
// в Бермудском Прямоугольнике. Клетка может находиться в Бермудском Прямоугольнике,
// если существует такой прямоугольник, который удовлетворяет заданным ограничениям
// Бермудского Прямоугольника и содержит в себе эту клетку. Помогите Бобру быстро
// отвечать на запросы! Нужно ответить на q таких запросов.

// Входные данные
// Каждый тест состоит из нескольких наборов входных данных. В первой строке находится
// одно целое число t (1 ≤ t ≤ 10000) — количество наборов входных данных. Далее следует
// описание наборов входных данных.

// Первая строка каждого набора содержит два целых числа S и q — площадь Бермудского
// Прямоугольника и количество запросов (1 ≤ S ≤ 10^12; 1 ≤ q ≤ 3·10^5).

// Далее следуют q строк, каждая из которых содержит два целых числа x, y —
// очередной запрос (1 ≤ x, y ≤ S).

// Гарантируется, что сумма значений q по всем наборам не превосходит 3·10^5.

// Гарантируется, что сумма значений √S по всем наборам не превосходит 10^6.

// Выходные данные
// Для каждого запроса выведите в отдельной строке одно целое число — ответ на запрос.

// ======================================================================
// Пример
// ======================================================================
// Входные данные
// ======================================================================
// 3
// 6 4
// 2 3
// 4 5
// 6 6
// 1 1
// 5 2
// 2 2
// 3 4
// 8 2
// 3 1
// 5 6
// ======================================================================
// Выходные данные
// ======================================================================
// 6
// 11
// 14
// 1
// 3
// 6
// 3
// 15
// ======================================================================

// Примечание
// В первом наборе входных данных для первого запроса подходит любая клетка
// прямоугольника (2, 3), так как сам этот прямоугольник может быть Бермудским.

// Второй запрос первого набора изображён на рисунке. Ответ на запрос — количество
// клеток в пересечении синей и красной фигур.

// 4 синих прямоугольника — возможные расположения Бермудского прямоугольника.
// Красный — прямоугольник запроса (x, y) = (4, 5).

// В третьем запросе первого набора учитывается любая клетка, которая может лежать
// хотя бы в одном из возможных Бермудских прямоугольников.

// В четвёртом запросе первого набора единственная клетка запроса может лежать
// в Бермудском прямоугольнике, поэтому ответ равен 1.

#include <bits/stdc++.h>
using namespace std;

using int64 = long long;

void solve()
{
    int64 S;
    int q;
    cin >> S >> q;

    vector<int64> divs;
    for (int64 d = 1; d * d <= S; ++d)
    {
        if (S % d == 0)
        {
            divs.push_back(d);
            if (d * d != S)
                divs.push_back(S / d);
        }
    }
    sort(divs.begin(), divs.end());

    int n = (int)divs.size();
    vector<int64> w(n), M(n), prefW(n + 1, 0), prefWM(n + 1, 0);

    int64 prev = 0;
    for (int i = 0; i < n; ++i)
    {
        int64 a = divs[i];
        w[i] = a - prev;
        M[i] = S / a;

        prefW[i + 1] = prefW[i] + w[i];
        prefWM[i + 1] = prefWM[i] + w[i] * M[i];

        prev = a;
    }

    while (q--)
    {
        int64 x, y;
        cin >> x >> y;

        int idx = lower_bound(divs.begin(), divs.end(), x) - divs.begin();
        int64 prevDiv = (idx == 0 ? 0 : divs[idx - 1]);

        int fullEnd = idx;
        int64 partLen = x - prevDiv;

        int l = 0, r = n;
        while (l < r)
        {
            int mid = (l + r) / 2;
            if (M[mid] <= y)
                r = mid;
            else
                l = mid + 1;
        }
        int i0 = l + 1;

        int64 ans = 0;

        int end1 = min(fullEnd, i0 - 1);
        if (end1 > 0)
        {
            ans += y * (prefW[end1] - prefW[0]);
        }

        int start2 = max(i0, 1);
        if (start2 <= fullEnd)
        {
            ans += prefWM[fullEnd] - prefWM[start2 - 1];
        }

        int64 curM = S / divs[idx];
        ans += partLen * min(y, curM);

        cout << ans << '\n';
    }
}

int main()
{
    ios::sync_with_stdio(false);
    cin.tie(nullptr);

    int t;
    cin >> t;
    while (t--)
    {
        solve();
    }

    return 0;
}