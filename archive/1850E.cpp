// У Мирчи есть n картин. i-я картина является квадратом со стороной s_i сантиметров.

// Он прикрепил каждую картину к квадратному куску картона так, чтобы у каждой картинки
// был картон шириной w сантиметров со всех сторон. Всего он использовал c квадратных
// сантиметров картона. Зная размеры картин и значение c, сможете ли вы найти значение w?

// (Картинка первого тестового примера. Здесь c = 50 = 5^2 + 4^2 + 3^2, поэтому ответ w = 1).

// Обратите внимание, что кусок картона находится за каждой картинкой, а не только по краям.

// Входные данные
// Первая строка содержит одно целое число t (1 ≤ t ≤ 1000) — количество наборов
// входных данных.

// Первая строка каждого набора содержит два положительных целых числа n (1 ≤ n ≤ 2·10^5)
// и c (1 ≤ c ≤ 10^18) — количество картин и количество использованных квадратных
// сантиметров картона.

// Вторая строка каждого набора содержит n целых чисел, разделённых пробелами,
// s_i (1 ≤ s_i ≤ 10^4) — размеры картин.

// Сумма n по всем наборам не превышает 2·10^5.2

// Дополнительное ограничение на ввод: Для каждого набора входных данных существует
// такое целое число w.

// Пожалуйста, обратите внимание, что некоторые наборы входных данных могут не
// поместиться в 32-разрядный целочисленный тип, поэтому вам следует использовать
// по крайней мере 64-разрядный целочисленный тип в вашем языке программирования
// (например, long long для C++).

// Выходные данные
// Для каждого набора входных данных выведите одно целое число — значение w (w ≥ 1),
// при котором понадобится ровно c квадратных сантиметров картона.

