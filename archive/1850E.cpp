// Примечание
// Первый пример объяснён в условии.

// Для второго примера выбрано значение w = 2, таким образом, площадь, покрытая
// картоном, составляет c = (2·2 + 6)^2 = 10^2 = 100 квадратных сантиметров.

// Для третьего примера выбрано значение w = 4, что даёт площадь покрытия
// c = (2·4 + 2)^2 · 5 = 10^2 · 5 = 100 · 5 = 500 квадратных сантиметров.

#include <bits/stdc++.h>
using namespace std;

#define int long long

bool check(vector<int> &a, int n, long double c, int x)
{

    for (int i = 0; i < n; i++)
        c -= (a[i] + 2 * x) * (a[i] + 2 * x);
    return c <= 0;
}

void solve()
{
    int n, c;
    cin >> n >> c;
    vector<int> a(n);
    for (auto &i : a)
        cin >> i;
    int l = 0, r = 1e10;
    while (r > l + 1)
    {
        int m = (l + r) / 2;
        if (check(a, n, c, m))
            r = m;
        else
            l = m;
    }
    cout << r << '\n';
}

int32_t main()
{
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);
    int t;
    cin >> t;
    while (t--)
    {
        solve();
    }
    return 0;
}
