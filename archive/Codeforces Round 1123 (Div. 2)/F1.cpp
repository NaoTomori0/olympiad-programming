// F1. XOR трансформации (простая версия)
// ограничение по времени на тест4 секунды
// ограничение по памяти на тест512 мегабайт

// Это простая версия задачи. Разница между версиями состоит в том, что в этой версии
// ограничения на n и q меньше. Взломы можно делать только если вы решили все версии
// этой задачи.

// Для массива b, состоящего из m целых чисел, определим трансформацию следующим образом:

// - Выпишем значения b_i ⊕ b_j для всех 1 ≤ i < j ≤ m, где ⊕ обозначает операцию
//   побитового исключающего ИЛИ.
// - Возьмём m наименьших среди выписанных значений.
// - Заменим элементы массива на взятые m значений.

// Например, рассмотрим трансформацию массива [6, 7, 8, 9, 15]. Мы выписываем значения
// 1, 1, 6, 7, 8, 9, 14, 14, 15, 15. После трансформации массив становится
// [1, 1, 6, 7, 8] — 5 наименьших элементов.

// Вам дан массив a, состоящий из n неотрицательных целых чисел. Пусть max(a) обозначает
// максимальный элемент массива a, а min(a) — минимальный. Ваша задача — ответить на q
// запросов, в каждом из которых вам даётся одно целое число x. Для каждого запроса
// найдите значение max(a) − min(a) после x трансформаций массива. Заметьте, что запросы
// независимы, то есть перед каждым запросом массив a возвращается в исходное состояние.

// Входные данные
// Каждый тест состоит из нескольких наборов входных данных. В первой строке находится
// одно целое число t (1 ≤ t ≤ 100) — количество наборов входных данных. Далее следует
// описание наборов входных данных.

// В первой строке каждого набора входных данных даны два целых числа n и q
// (5 ≤ n ≤ 2000, 1 ≤ q ≤ 2000) — размер массива и количество запросов.

// Во второй строке каждого набора входных данных даны n целых чисел a1, a2, …, a_n
// (0 ≤ a_i < 2^30).

// Следующие q строк каждого набора входных данных содержат по одному целому числу x
// (0 ≤ x < 2^30).

// Гарантируется, что сумма n и сумма q по всем наборам входных данных не превосходят 2000.

// Выходные данные
// Для каждого набора входных данных выведите q целых чисел — ответ на каждый запрос.

// ======================================================================
// Пример
// ======================================================================
// Входные данные
// ======================================================================
// 4
// 5 1
// 0 0 1 1 1
// 1
// 5 2
// 6 7 8 9 15
// 0
// 1
// 8 2
// 102 92 15 19 25 54 62 36
// 2
// 1
// 10 1
// 56 73 81 23 17 92 50 34 67 78
// 2
// ======================================================================
// Выходные данные
// ======================================================================
// 1
// 9
// 7
// 12
// 31
// 7
// ======================================================================

// Примечание
// В первом наборе входных данных после одной трансформации массив становится
// [0, 0, 0, 0, 1]. Здесь max(a) − min(a) = 1 − 0 = 1.

// Во втором наборе входных данных массив равен [6, 7, 8, 9, 15]. Изначально
// max(a) − min(a) = 15 − 6 = 9. После трансформации массив становится [1, 1, 6, 7, 8],
// где max(a) − min(a) = 8 − 1 = 7.

#include <bits/stdc++.h>
using namespace std;

#define int long long

void solve()
{
    int n, q;
    cin >> n >> q;
    vector<int> a(n);
    for (int i = 0; i < n; i++)
    {
        cin >> a[i];
    }

    vector<int> qus(q);
    int max_x = 0;
    for (int i = 0; i < q; i++)
    {
        cin >> qus[i];
        max_x = max(max_x, qus[i]);
    }
    const int LIMIT = 100;
    vector<int> res;

    int mnv = *min_element(a.begin(), a.end());
    int mxv = *max_element(a.begin(), a.end());
    res.push_back(mxv - mnv);

    vector<int> cur = a;

    for (int st = 1; st <= LIMIT; st++)
    {
        if (mxv == 0)
            break;

        vector<int> p;
        p.reserve(n * (n - 1) / 2);

        for (int i = 0; i < n; i++)
        {
            for (int j = i + 1; j < n; j++)
            {
                p.push_back(cur[i] ^ cur[j]);
            }
        }

        sort(p.begin(), p.end());
        p.resize(n);
        cur = p;

        mnv = cur[0];
        mxv = cur[n - 1];
        res.push_back(mxv - mnv);
    }

    for (int i = 0; i < q; i++)
    {
        int x = qus[i];
        if (x >= (int)res.size())
            cout << res.back() << "\n";
        else
            cout << res[x] << "\n";
    }
}

int32_t main()
{
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);

    int t;
    cin >> t;
    while (t--)
    {
        solve();
    }
    return 0;
}
