// D. Знаки префиксных сумм
// ограничение по времени на тест2 секунды
// ограничение по памяти на тест512 мегабайт

// Для массива a1, a2, …, a_n из целых чисел, в котором ни один элемент не равен 0,
// определим префиксные суммы как массив p1, p2, …, p_n, где p_i равно сумме первых
// i элементов массива a.

// По массиву префиксных сумм строится строка s длины n: её i-й символ равен '+',
// если p_i > 0, '-', если p_i < 0, и '0', если p_i = 0.

// Например, для массива a = [2, −1, −1, −2, 2] префиксные суммы равны
// p = [2, 1, 0, −2, 0]. Поэтому соответствующая строка будет "++0-0".

// Стоимостью массива a назовём величину max_{1 ≤ i ≤ n} |a_i|.

// Вам дана строка s. Найдите минимально возможную стоимость целочисленного массива a,
// по которому могла быть получена эта строка. Все элементы массива a должны быть
// ненулевыми. Если такого массива не существует, выведите −1.

// Входные данные
// В первой строке дано целое число t (1 ≤ t ≤ 10^4) — количество наборов входных данных.

// Каждый набор входных данных состоит из двух строк. Первая строка содержит целое
// число n (1 ≤ n ≤ 3·10^5) — длину строки s. Вторая строка содержит последовательность s
// длины n, состоящую из символов '0', '+' и/или '-'.

// Дополнительные ограничения на входные данные:

// - сумма n по всем наборам входных данных не превосходит 3·10^5.

// Выходные данные
// Для каждого набора входных данных выведите одно целое число — минимально возможную
// стоимость массива a или −1, если подходящего массива не существует.

// ======================================================================
// Пример
// ======================================================================
// Входные данные
// ======================================================================
// 6
// 1
// +
// 1
// 0
// 3
// ++0
// 4
// +--+
// 5
// +---+
// 5
// +0++-
// ======================================================================
// Выходные данные
// ======================================================================
// 1
// -1
// 2
// 3
// 2
// 2
// ======================================================================

// Примечание
// Оптимальные массивы a в наборах входных данных в примере из условия:

// - [1];
// - нет подходящего массива;
// - [2, −1, −1];
// - [1, −3, 1, 2];
// - [1, −2, −1, 1, 2];
// - [2, −2, 2, −1, −2].

#include <bits/stdc++.h>
using namespace std;

#define int long long

bool check(const string &s, int m)
{
    const int OFFSET = 15;
    vector<bool> current_p(30, false);
    current_p[OFFSET] = true;

    for (char c : s)
    {
        vector<bool> next_p(30, false);
        bool any = false;

        for (int p = -12; p <= 12; ++p)
        {
            if (!current_p[p + OFFSET])
                continue;

            for (int a = -m; a <= m; ++a)
            {
                if (a == 0)
                    continue;
                int np = p + a;

                if (c == '+' && np <= 0)
                    continue;
                if (c == '-' && np >= 0)
                    continue;
                if (c == '0' && np != 0)
                    continue;

                next_p[np + OFFSET] = true;
                any = true;
            }
        }

        if (!any)
            return false;
        current_p = move(next_p);
    }
    return true;
}

void solve()
{
    int n;
    string s;
    cin >> n >> s;

    for (int m = 1; m <= 3; ++m)
    {
        if (check(s, m))
        {
            cout << m << '\n';
            return;
        }
    }
    cout << -1 << '\n';
}

int32_t main()
{
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);
    int t;
    cin >> t;
    while (t--)
        solve();
    return 0;
}
