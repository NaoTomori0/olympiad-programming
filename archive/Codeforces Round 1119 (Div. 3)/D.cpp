// D. MEX мультимножеств
// ограничение по времени на тест2 секунды
// ограничение по памяти на тест256 мегабайт

// Дан массив a1, a2, …, a_n. Существуют 3 изначально пустых мультимножества A, B, C,
// и для каждого индекса i (1 ≤ i ≤ n) вы можете положить a_i ровно в одно из A, B или C.

// Определите, возможно ли распределить элементы по мультимножествам так, чтобы
// MEX(A) + MEX(B) + MEX(C) ≥ 2·max(MEX(A), MEX(B), MEX(C))*.
// Если да, выведите одно из таких распределений.

// * MEX(D) определяется как наименьшее неотрицательное целое число, которого нет
// в множестве D. Например, MEX([1, 2, 0, 5]) = 3, а MEX([1, 2, 4, 9]) = 0.
// MEX пустого множества равен 0.

// Входные данные
// Первая строка каждого набора входных данных содержит t (1 ≤ t ≤ 10^4) —
// количество наборов входных данных.

// Первая строка каждого набора входных данных содержит n (3 ≤ n ≤ 2·10^5) —
// длину массива a.

// Вторая строка каждого набора входных данных содержит a1, a2, …, a_n (0 ≤ a_i ≤ 10^9) —
// массив a.

// Гарантируется, что сумма n по всем наборам входных данных не превышает 2·10^5.

// Выходные данные
// Если существует корректное распределение элементов по мультимножествам, выведите YES.
// Иначе выведите NO.

// Если ответ YES, выведите на новой строке строку s длины n такую, что s_i = 'A',
// если i-й элемент был помещён в мультимножество A, s_i = 'B', если i-й элемент был
// помещён в мультимножество B, и s_i = 'C', если i-й элемент был помещён
// в мультимножество C.

// Вы можете выводить ответ в любом регистре (верхнем или нижнем). Например, строки YES,
// yes, yEs и Yes будут распознаны как положительные ответы, а строки NO, no, No
// будут распознаны как отрицательные ответы. Кроме того, строки AABCAAA, aabcaaa
// и aaBcaaa будут распознаны как один и тот же ответ.

// Если возможных ответов несколько, выведите любой.

// ======================================================================
// Пример
// ======================================================================
// Входные данные
// ======================================================================
// 5
// 6
// 1 0 0 1 2 1
// 4
// 0 0 0 0
// 3
// 0 2 2
// 4
// 6 7 6 7
// 5
// 0 0 0 1 2
// ======================================================================
// Выходные данные
// ======================================================================
// YES
// ABABCA
// YES
// ABAC
// NO
// YES
// AAAB
// YES
// ABCAB
// ======================================================================

// Примечание
// В первом наборе входных данных можно взять A = {0, 1}, B = {0, 1}, C = {1, 2},
// то есть MEX(A) + MEX(B) + MEX(C) = 4, а 2·max(MEX(A), MEX(B), MEX(C)) =
// 2·max(2, 2, 0) = 4.

// В третьем наборе входных данных можно показать, что корректных распределений
// не существует.
#include <iostream>
#include <vector>
#include <string>
#include <map>
#include <algorithm>

using namespace std;

void solve()
{
    int n;
    cin >> n;

    vector<long long> a(n);
    map<long long, vector<int>> pos;

    for (int i = 0; i < n; ++i)
    {
        cin >> a[i];
        pos[a[i]].push_back(i);
    }

    int x = 0;
    while (pos.count(x) && pos[x].size() >= 2)
    {
        x++;
    }

    int ans_y = -1;
    int ans_z = -1;

    for (int y = x; y <= n + 1; ++y)
    {
        bool ok = true;
        for (int i = x; i < y; ++i)
        {
            if (!pos.count(i) || pos[i].empty())
            {
                ok = false;
                break;
            }
        }
        if (!ok)
            break;

        int z = 0;
        while (true)
        {
            int cnt = pos.count(z) ? pos[z].size() : 0;
            if (z < x)
            {
                cnt -= 2;
            }
            else if (z >= x && z < y)
            {
                cnt -= 1;
            }

            if (cnt > 0)
            {
                z++;
            }
            else
            {
                break;
            }
        }

        if (x + y + z >= 2 * max({x, y, z}))
        {
            ans_y = y;
            ans_z = z;
            break;
        }
    }

    if (ans_y != -1)
    {
        cout << "YES\n";
        string s(n, 'C');

        for (int i = 0; i < x; ++i)
        {
            s[pos[i][0]] = 'A';
        }
        for (int i = 0; i < ans_y; ++i)
        {
            if (i < x)
            {
                s[pos[i][1]] = 'B';
            }
            else
            {
                s[pos[i][0]] = 'B';
            }
        }
        cout << s << "\n";
    }
    else
    {
        cout << "NO\n";
    }
}

int main()
{
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);

    int t;
    cin >> t;
    while (t--)
    {
        solve();
    }
    return 0;
}
