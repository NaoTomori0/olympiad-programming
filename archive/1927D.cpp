#include <bits/stdc++.h>
using namespace std;

#define int long long

void solve()
{
    int n, q;
    cin >> n;
    vector<int> a(n), p(n, -1);
    for (auto &i : a)
        cin >> i;
    for (int i = 1; i < n; i++)
    {
        p[i] = p[i - 1];
        if (a[i] != a[i - 1])
            p[i] = i - 1;
    }

    cin >> q;
    while (q--)
    {
        int l, r;
        cin >> l >> r;
        r--;
        l--;
        if (p[r] >= l)
            cout << p[r] + 1 << ' ' << r + 1 << '\n';
        else
            cout << "-1 -1\n";
    }
    cout << '\n';
}

int32_t main()
{
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);
    int t;
    cin >> t;
    while (t--)
    {
        solve();
    }
    return 0;
}
