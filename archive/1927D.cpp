// - l ≤ i ≤ r;
// - l ≤ j ≤ r;
// - a_i ≠ a_j.

// Иными словами, вам нужно для каждого запроса найти пару различных элементов среди
// a_l, a_{l+1}, …, a_r или сообщить, что такой пары не существует.

// Входные данные
// Первая строка входных данных содержит одно целое число t (1 ≤ t ≤ 10^4) — количество
// наборов входных данных. Далее следуют описания наборов.

// Первая строка каждого набора содержит одно целое число n (2 ≤ n ≤ 2·10^5) — длину
// массива a.

// Вторая строка каждого набора содержит n целых чисел a1, a2, …, a_n (1 ≤ a_i ≤ 10^6) —
// элементы массива a.

// Третья строка каждого набора содержит одно целое число q (1 ≤ q ≤ 2·10^5) —
// количество запросов.

// Следующие q строк содержат по два целых числа l и r (1 ≤ l < r ≤ n) — границы запроса.

// Гарантируется, что сумма значений n по всем наборам не превышает 2·10^5. Аналогично,
// сумма значений q по всем наборам не превышает 2·10^5.

// Выходные данные
// Для каждого запроса выведите два числа: искомые i и j (l ≤ i, j ≤ r), для которых
// a_i ≠ a_j. Если такой пары не существует, выведите i = −1 и j = −1.

// Вы можете разделять выводы для наборов входных данных пустыми строками. Это не
