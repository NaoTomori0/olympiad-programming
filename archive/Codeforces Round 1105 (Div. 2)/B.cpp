// описание наборов входных данных.

// Каждый набор входных данных состоит из одной строки, содержащей четыре целых числа
// n, m, r, c (1 ≤ r ≤ n ≤ 10^9, 1 ≤ c ≤ m ≤ 10^9) — размеры матрицы и размеры
// области сканирования соответственно.

// Выходные данные
// Для каждого набора входных данных выведите единственное целое число — ответ по модулю 998244353.

