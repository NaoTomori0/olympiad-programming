// E. Дружеские подарки
// ограничение по времени на тест3 секунды
// ограничение по памяти на тест512 мегабайт
// Арсений решил порадовать своих друзей — Дабира и Егора. Для этого он решил подарить каждому из них по массиву чисел одинаковой длины. Массив b
//  называется хорошим, если его элементы можно переставить так, что для всех i>1
//  верно bi−bi−1=1
// .

// Арсений хочет, чтобы Дабир и Егор могли играть с этими массивами. Для этого должны быть выполнены следующие условия:

// Каждый из подаренных массивов является хорошим.
// Если записать один массив за вторым(другими словами, сконкатенировать), полученный массив окажется хорошим.
// У Арсения уже есть массив a
//  длины n
// . Он планирует вырезать оба массива из a
// , то есть выбрать в нём два непересекающихся отрезка одинаковой длины. Помогите Арсению определить максимальную возможную длину полученных массивов.

// Входные данные
// В первой строке находится одно целое число t
//  (1≤t≤1000)
//  — количество наборов входных данных.

// Далее следуют t
//  наборов входных данных.

// Первая строка каждого набора входных данных содержит одно целое число n
//  (1≤n≤6000)
// .

// Вторая строка содержит n
//  целых чисел a1,a2,…,an
//  (1≤ai≤n)
// .

// Гарантируется, что сумма значений n
//  по всем наборам входных данных не превосходит 6000
// .

// Выходные данные
// Для каждого набора входных данных выведите целое число, обозначающее максимальную возможную длину массивов.

// Пример
// Входные данныеСкопировать
// 7
// 1
// 1
// 2
// 1 2
// 3
// 2 1 1
// 4
// 2 1 4 3
// 5
// 1 2 4 5 3
// 6
// 3 2 1 6 5 4
// 10
// 1 1 2 3 4 1 6 5 7 8
// Выходные данныеСкопировать
// 0
// 1
// 1
// 2
// 1
// 3
// 4
// Примечание
// В первом наборе входных данных невозможно выбрать 2
//  массива, поэтому ответ 0
// .

// Во втором наборе входных данных максимальная длина выбранных массивов равна 1
// . Можно выбрать массивы [1
// ] и [2
// ].

// В четвертом наборе входных данных максимальная длина выбранных массивов равна 2
// . Можно выбрать массивы [2,1
// ] и [4,3
// ].

// В пятом наборе входных данных максимальная длина выбранных массивов равна 1
// . Одним из способов выбрать массивы – [1
// ] и [2
// ]. Другими способами являются массивы [2
// ] и [3
// ], [3
// ] и [4
// ], или [4
// ] и [5
// ].

#include <bits/stdc++.h>
using namespace std;

int main()
{
    ios::sync_with_stdio(false);
    cin.tie(0);
    int t;
    cin >> t;
    while (t--)
    {
        int n;
        cin >> n;
        vector<int> a(n);
        for (int i = 0; i < n; ++i)
            cin >> a[i];
        int maxL = n / 2;
        const int INF = n + 5;
        vector<int> min_r((maxL + 1) * (n + 1), INF);
        vector<int> max_l((maxL + 1) * (n + 1), -1);
        vector<int> last(n + 1, -1);
        for (int l = 0; l < n; ++l)
        {
            int min_v = a[l], max_v = a[l];
            last[a[l]] = l;
            if (1 <= maxL)
            {
                int x = min_v;
                int idx = 1 * (n + 1) + x;
                if (l < min_r[idx])
                    min_r[idx] = l;
                if (l > max_l[idx])
                    max_l[idx] = l;
            }
            for (int r = l + 1; r < n; ++r)
            {
                int v = a[r];
                if (last[v] >= l)
                    break;
                last[v] = r;
                if (v < min_v)
                    min_v = v;
                if (v > max_v)
                    max_v = v;
                if (max_v - min_v == r - l)
                {
                    int len = r - l + 1;
                    if (len <= maxL)
                    {
                        int x = min_v;
                        int idx = len * (n + 1) + x;
                        if (r < min_r[idx])
                            min_r[idx] = r;
                        if (l > max_l[idx])
                            max_l[idx] = l;
                    }
                }
            }
        }
        int ans = 0;
        for (int len = maxL; len >= 1; --len)
        {
            for (int x = 1; x + 2 * len - 1 <= n; ++x)
            {
                int idx1 = len * (n + 1) + x;
                int idx2 = len * (n + 1) + x + len;
                if (min_r[idx1] != INF && max_l[idx2] != -1)
                {
                    if (min_r[idx1] < max_l[idx2] || min_r[idx2] < max_l[idx1])
                    {
                        ans = len;
                        break;
                    }
                }
            }
            if (ans)
                break;
        }
        cout << ans << '\n';
    }
    return 0;
}