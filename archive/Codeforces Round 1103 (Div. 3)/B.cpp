// B. Татарское телешоу
// ограничение по времени на тест2 секунды
// ограничение по памяти на тест256 мегабайт

// На каникулах Егор приехал к своему другу Дабиру в город Казань. От скуки Дабир и Егор
// придумали новую бизнес-идею: снимать собственное телешоу.

// Формат телешоу очень простой: в каждом выпуске они приглашают гостя и играют с ним
// в игру на бинарной строке.

// В сегодняшнем выпуске Егор и Дабир пригласили Арсения (aka MAKAN) — главную знаменитость
// Омска. Для игры они выбрали бинарную строку s длины n и число k.

// Арсению разрешается выполнять неограниченное количество ходов. За один ход он может
// выбрать число i (1 ≤ i ≤ n−k) и инвертировать символы на позициях i и i+k, то есть
// заменить 0 на 1, а 1 на 0.

// Например, если s = 10110 и k = 2, то выбрав i = 2, Арсений инвертирует символы
// на позициях 2 и 4: [10110 → 11100].

// Арсений хочет получить главный приз — 1000000 тугриков. Для этого ему необходимо
// сделать всю строку s нулевой.

// Помогите Арсению определить, сможет ли он получить свой приз, или ему придётся
// уехать в Омск ни с чем.

// Входные данные
// Первая строка содержит одно целое число t (1 ≤ t ≤ 10^4) — количество наборов
// входных данных.

// Первая строка каждого набора содержит два целых числа n и k (1 ≤ k ≤ n ≤ 2·10^5).

// Вторая строка каждого набора содержит бинарную строку s длины n.

// Гарантируется, что сумма значений n по всем наборам входных данных не превосходит 2·10^5.

// Выходные данные
// Для каждого набора входных данных выведите «YES», если Арсений сможет сделать строку
// полностью нулевой, и «NO» в противном случае.

// Вы можете выводить «YES» и «NO» в любом регистре (например, строки «yES», «yes»
// и «Yes» будут распознаны как правильный ответ).

// ======================================================================
// Пример
// ======================================================================
// Входные данные
// ======================================================================
// 5
// 4 2
// 1010
// 3 2
// 111
// 3 3
// 111
// 3 1
// 110
// 1 1
// 1
// ======================================================================
// Выходные данные
// ======================================================================
// YES
// NO
// NO
// YES
// NO
// ======================================================================

#include <iostream>
#include <vector>
#include <string>

using namespace std;

void solve()
{
    int n, k;
    cin >> n >> k;

    string s;
    cin >> s;

    vector<int> count_ones(k, 0);

    for (int i = 0; i < n; i++)
    {
        if (s[i] == '1')
        {
            count_ones[i % k]++;
        }
    }

    // Проверяем каждую группу на четность
    for (int i = 0; i < k; i++)
    {
        if (count_ones[i] % 2 != 0)
        {
            cout << "NO\n";
            return;
        }
    }

    cout << "YES\n";
}

int main()
{
    // Быстрый ввод-вывод
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);

    int t;
    cin >> t;
    while (t--)
    {
        solve();
    }
    return 0;
}
