// F1. Выборы в Саранске (простая версия)
// ограничение по времени на тест4 секунды
// ограничение по памяти на тест256 мегабайт

// Это простая версия задачи. Единственное отличие в том, что x = 1.

// По пути домой после покупки своей любимой газировки «Zola Cero» Егор увидел,
// что в Саранске проходят выборы на пост «Лучшее число».

// На избирательном участке находятся n человек. Каждый человек принёс с собой
// число a_i. Когда i-й человек заходит в кабинку для голосования, он выбирает
// кандидата, который является делителем числа a_i. Обозначим выбранного кандидата
// через p_i.

// После того как все проголосовали, получился массив голосов [p_1, p_2, …, p_n].

// Егор очень любит число x и считает голосование идеальным, если

// x · lcm(p_1, p_2, …, p_n) = p_1 · p_2 · … · p_n.

// Помогите ему найти количество различных* массивов p по модулю 10^9+7, которые
// являются идеальными.

// * lcm — наименьшее общее кратное.
// † Два массива голосов считаются различными, если существует индекс i,
//   в котором два массива имеют отличные друг от друга элементы.

// Входные данные
// В первой строке записано одно целое число t (1 ≤ t ≤ 10^4) — количество наборов
// входных данных.

// Далее следуют t наборов входных данных.

// В первой строке каждого набора записаны два целых числа n и x (1 ≤ n ≤ 10^5, x = 1)
// — число голосующих на избирательном участке и любимое число Егора.

// Во второй строке каждого набора записаны n целых чисел: a_1, a_2, …, a_n
// (1 ≤ a_i ≤ 5·10^5) — числа, которые принесли с собой голосующие.

// Гарантируется, что сумма n по всем наборам входных данных не превосходит 10^5.

// Выходные данные
// Для каждого набора входных данных выведите количество способов по модулю 10^9+7
// проголосовать так, чтобы итоговый массив голосов удовлетворял условию.

// ======================================================================
// Пример
// ======================================================================
// Входные данные
// ======================================================================
// 4
// 4 1
// 2 3 1 4
// 2 1
// 2 4
// 6 1
// 3 9 1 6 4 5
// 7 1
// 1 2 3 67 13 8 8
// ======================================================================
// Выходные данные
// ======================================================================
// 8
// 4
// 40
// 64
// ======================================================================

#include <bits/stdc++.h>
using namespace std;

const int MAXA = 500000;
const int MOD = 1'000'000'007;

vector<int> spf;

void build_spf()
{
    spf.assign(MAXA + 1, 0);
    for (int i = 2; i <= MAXA; ++i)
    {
        if (spf[i] == 0)
        {
            spf[i] = i;
            if ((long long)i * i <= MAXA)
            {
                for (int j = i * i; j <= MAXA; j += i)
                {
                    if (spf[j] == 0)
                        spf[j] = i;
                }
            }
        }
    }
}

int main()
{
    ios::sync_with_stdio(false);
    cin.tie(0);
    build_spf();

    int t;
    cin >> t;
    vector<long long> sum_v(MAXA + 1, 0);
    vector<int> used;
    while (t--)
    {
        int n, x;
        cin >> n >> x;
        used.clear();
        for (int i = 0; i < n; ++i)
        {
            int val;
            cin >> val;
            while (val > 1)
            {
                int p = spf[val];
                int cnt = 0;
                while (val % p == 0)
                {
                    val /= p;
                    ++cnt;
                }
                if (sum_v[p] == 0)
                {
                    used.push_back(p);
                }
                sum_v[p] += cnt;
            }
        }
        long long ans = 1;
        for (int p : used)
        {
            ans = ans * (1 + sum_v[p]) % MOD;
            sum_v[p] = 0;
        }
        cout << ans << '\n';
    }
    return 0;
}