// Примечание
// В первом наборе тестовых данных, где n = 1, ответ 1, поскольку достаточно
// использовать одну монету стоимости 1.

// В четвёртом наборе входных данных, где n = 5, ответ 3, который может быть достигнут,
// используя две монеты стоимости 1 и одну монету стоимости 3.

// В седьмом наборе входных данных, где n = 12, ответ 2, который может быть достигнут,
// используя две монеты стоимости 6.

// В девятом наборе входных данных, где n = 16, ответ 2, который может быть достигнут,
// используя одну монету стоимости 1 и одну монету стоимости 15. Альтернативным
// решением может быть использование одной монеты стоимости 10 и одной монеты
// стоимости 6.

#include <bits/stdc++.h>
using namespace std;

#define int long long

void solve(vector<int> &dp)
{
    int n;
    cin >> n;
    if (n <= 100)
    {
        cout << dp[n] << '\n';
        return;
    }

    int cn15 = n / 15, res = 1e18;
    for (int i = max(0LL, cn15 - 4); i < cn15; i++)
    {
        int r = n - 15 * i;
        if (r <= 100)
            res = min(res, i + dp[r]);
    }

    cout << res << '\n';
}

int32_t main()
{
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);
    int t;
    cin >> t;
    vector<int> dp(101, 1e10);
    dp[0] = 0;
    for (int i = 1; i <= 100; i++)
    {
        dp[i] = dp[i - 1] + 1;
        if (i >= 3)
            dp[i] = min(dp[i], dp[i - 3] + 1);
        if (i >= 6)
            dp[i] = min(dp[i], dp[i - 6] + 1);
        if (i >= 10)
            dp[i] = min(dp[i], dp[i - 10] + 1);
        if (i >= 15)
            dp[i] = min(dp[i], dp[i - 15] + 1);
    }
    while (t--)
    {
        solve(dp);
    }
    return 0;
}

