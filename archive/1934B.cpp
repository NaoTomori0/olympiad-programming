// У вас есть 5 различных типов монет, каждый из которых имеет значение, равное одному
// из первых 5 треугольных чисел: 1, 3, 6, 10 и 15. Все типы монет имеются
// в неограниченном количестве. Ваша задача — определить, какого минимального
// количества монет достаточно, чтобы набрать сумму ровно n.

// Можно показать, что ответ всегда существует.

// Входные данные
// В первой строке находится одно целое число t (1 ≤ t ≤ 10^4) — количество наборов
// входных данных. Далее следует описание наборов входных данных.

// В единственной строке каждого набора входных данных содержится одно целое число n
// (1 ≤ n ≤ 10^9) — требуемое значение.

// Выходные данные
// Для каждого набора входных данных выведите одно число — минимальное необходимое
// количество монет.

// ======================================================================
// Пример
// ======================================================================
// Входные данные
// ======================================================================
// 14
// 1
// 2
