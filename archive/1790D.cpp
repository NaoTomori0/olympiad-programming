// Примечание
// Первый набор входных данных разобран в условии.

// Во втором наборе входных данных все матрёшки могли быть частью одного набора
// с минимальным размером матрёшки s = 7.

// В третьем наборе входных данных каждая матрёшка представляет собой отдельный набор.

#include <bits/stdc++.h>
using namespace std;

#define int long long

void solve()
{
    int n;
    cin >> n;
    map<int, int> a;
    for (int i = 0; i < n; i++)
    {
        int x;
        cin >> x;
        a[x]++;
    }
    int res = 0;
    for (auto &i : a)
    {
        while (i.second > 0)
        {
            for (int j = 1; a[i.first + j] > 0; j++)
                a[i.first + j]--;
            i.second--;
            res++;
        }
    }
    cout << res << '\n';
}
// 1 2 2 3 3 4
int32_t main()
{
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);
    int t;
    cin >> t;
    while (t--)
    {
        solve();
    }
    return 0;
}
