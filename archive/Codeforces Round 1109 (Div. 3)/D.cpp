// D. Ярослав и продуктивность
// ограничение по времени на тест2 секунды
// ограничение по памяти на тест256 мегабайт

// Продуктивность Ярослава в течение дня описывается массивом a длины n.
// Продуктивность Ярослава может быть отрицательной, если Ярослав смотрит короткие видео,
// или положительной, если Ярослав работает. Назовём общей продуктивностью сумму всей
// продуктивности Ярослава за день.

// Иногда Ярослав читает мотивационные посты. У него есть m постов, j-й пост имеет силу
// воздействия b_j. Если Ярослав прочитает пост с силой b_j, то вся продуктивность
// Ярослава с начала дня до момента b_j изменится на противоположную, то есть все числа
// a1, a2, a3, …, a_{b_j} умножатся на −1.

// Например, пусть продуктивность описывается массивом a = [1, −4, 3, −4], и Ярослав
// читает пост с силой 3. Тогда знаки первых трёх элементов изменятся на противоположные,
// и массив станет равен [−1, 4, −3, −4]. Если затем он прочитает пост с силой 1,
// знак первого элемента снова изменится, и массив примет вид [1, 4, −3, −4].

// Какую максимальную общую продуктивность за день может иметь Ярослав, прочитав любые
// (возможно, никакие) мотивационные посты?

// Входные данные
// В первой строке вводится единственное число t (1 ≤ t ≤ 10^4) — количество наборов
// входных данных.

// В первой строке каждого набора входных данных вводятся два числа n и m
// (1 ≤ m ≤ n ≤ 2·10^5) — количество измерений продуктивности и количество мотивационных
// постов.

// Во второй строке каждого набора входных данных вводится массив n целых чисел a_i
// (−10^9 ≤ a_i ≤ 10^9) — результаты измерений продуктивности Ярослава.

// В третьей строке каждого набора входных данных вводится массив m целых чисел b_i
// (1 ≤ b_i ≤ n) — силы воздействия мотивационных постов. Гарантируется, что все b_i
// различны.

// Гарантируется, что сумма n по всем наборам входных данных не превосходит 2·10^5.

// Выходные данные
// Для каждого набора входных данных в отдельной строке выведите единственное целое
// число — максимальную возможную общую продуктивность.

// ======================================================================
// Пример
// ======================================================================
// Входные данные
// ======================================================================
// 4
// 5 3
// -1 2 -3 4 -5
// 1 5 3
// 4 2
// 3 -1 3 -1
// 4 2
// 3 1
// -5 -5 -5
// 2
// 4 3
// 3 -1 1 -3
// 4 3 2
// ======================================================================
// Выходные данные
// ======================================================================
// 3
// 4
// 5
// 6
// ======================================================================

#include <bits/stdc++.h>
using namespace std;

#define int long long

void solve()
{
    int n, m;
    cin >> n >> m;
    vector<int> a(n);
    for (int i = 0; i < n; i++)
        cin >> a[i];

    vector<int> b(m);
    for (int i = 0; i < m; i++)
        cin >> b[i];

    // 1. Сортируем посты, чтобы идти по массиву отрезками
    sort(b.begin(), b.end());

    int total_sum = 0;
    int current_idx = 0;

    for (int i = 0; i < m; i++)
    {
        int segment_sum = 0;
        while (current_idx < b[i])
        {
            segment_sum += a[current_idx];
            current_idx++;
        }
        total_sum += abs(segment_sum);
    }

    int last_segment_sum = 0;
    while (current_idx < n)
    {
        last_segment_sum += a[current_idx];
        current_idx++;
    }
    total_sum += last_segment_sum;

    cout << total_sum << '\n';
}

int32_t main()
{
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);
    int t;
    cin >> t;
    while (t--)
    {
        solve();
    }
    return 0;
}
