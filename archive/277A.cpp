// ======================================================================
// 2 2
// 1 2
// 0
// ======================================================================
// Выходные данные
// ======================================================================
// 1
// ======================================================================

// Примечание
// Во втором примере сотрудник с номером 1 может выучить язык с номером 2, а сотрудник
// с номером 8 — язык с номером 4.

// В третьем примере сотруднику с номером 2 нужно выучить язык с номером 2.

#include <bits/stdc++.h>
using namespace std;

#define int long long

struct DSU
{
    DSU(int s, int s2)
    {
        parents.resize(s);
        p2.resize(s2);
        for (int i = 0; i < s; i++)
            parents[i] = i;
    }

    int find(int v)
    {
        if (v == parents[v])
            return v;
        return parents[v] = find(parents[v]);
    }

    void unite(int l, int r)
    {
        int pl = find(l), pr = find(r);
        if (pl != pr)
        {
            parents[pl] = pr;
        }
    }

    void add(int x, int i)
    {
        p2[x] = i;
    }

    vector<int> parents, p2;
};

void solve()
{
    int n, m;
    cin >> n >> m;
    DSU d(m, n);
    vector<int> gr(n, -1);
    for (int i = 0; i < n; i++)
    {
        int k;
        cin >> k;
        vector<int> a(k);
        for (auto &j : a)
        {
            cin >> j;
            j--;
        }
        // d.p2[i] = i;
        if (a.size() > 0)
            gr[i] = a[0];
        for (int j = 1; j < k; j++)
            d.unite(a[j - 1], a[j]);
    }
    int res = 0;
    set<int> cnt;
    for (int i = 0; i < n; i++)
    {
        if (gr[i] != -1)
            cnt.insert(d.parents[d.find(gr[i])]);
        else
            res++;
    }
    cout << cnt.size() + res - (cnt.size() > 0);
}

int32_t main()
{
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);

    solve();
    return 0;
}
