// В компании «BerCorp» работает n сотрудников. Для официальной переписки утверждено m
// языков, пронумерованных целыми числами от 1 до m. Для каждого сотрудника известно,
// какие языки он знает. Возможно даже, что человек не знает ни одного официального
// языка. Но работники готовы выучить любое количество языков, если только компания
// оплатит им обучение. Стоимость курса изучения одного языка для одного сотрудника
// составляет 1 бердоллар.

// Определите, какую минимальную сумму денег придётся затратить компании, чтобы любой
// сотрудник мог обратиться к любому другому, возможно, не напрямую (то есть, привлекая
// других сотрудников для перевода).

// Входные данные
// В первой строке записано два целых числа n и m (2 ≤ n, m ≤ 100) — количество
// сотрудников и количество языков.

// Далее следует n строк — списки языков для каждого работника. В начале i-ой строки
// записано целое число k_i (0 ≤ k_i ≤ m) — количество языков, которые знает i-ый
// сотрудник. Далее в i-ой строке записано k_i целых чисел — a_{ij} (1 ≤ a_{ij} ≤ m) —
// номера языков, которые знает i-ый сотрудник. Гарантируется, что все номера в одном
// списке различны. Обратите внимание, что сотрудник может не знать ни одного языка.

// Числа в строках разделяются одиночными пробелами.

// Выходные данные
// Выведите единственное целое число — наименьшее количество денег, которое придётся
// заплатить, чтобы каждый мог написать письмо каждому (возможно, привлекая других
// для перевода).

// ======================================================================
// Примеры
// ======================================================================
// Входные данные
// ======================================================================
// 5 5
// 1 2
// 2 2 3
// 2 3 4
// 2 4 5
// 1 5
// ======================================================================
// Выходные данные
// ======================================================================
